//! Version, channel and update source of this build (baked in by `build.rs` from env vars).

/// Full version: `0.2.0`, `0.2.0-rc.1`, `0.2.0-nightly.20261110`
pub(crate) const VERSION: &str = env!("ARKE_VERSION");
/// Short commit hash (empty when built outside git)
pub(crate) const COMMIT: &str = env!("ARKE_COMMIT");
/// GitHub repo with releases (`owner/name`); empty disables update checks
pub(crate) const RELEASES_REPO: &str = env!("ARKE_RELEASES_REPO");
/// Where Arke's source code is published (Settings › About › Source code).
pub(crate) const SOURCE_URL: &str = "https://github.com/Koimsurai/Arke";
/// Full license texts of the crates in this exe, generated by `cargo xtask licenses`
/// (Settings › About › Licenses).
pub(crate) const THIRD_PARTY_LICENSES: &str = include_str!("../../../THIRD_PARTY_LICENSES.md");

/// Release channel, ordered from most stable to newest.
#[derive(
    Clone,
    Copy,
    Debug,
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    serde::Serialize,
    serde::Deserialize,
    Default,
)]
#[serde(rename_all = "lowercase")]
pub(crate) enum Channel {
    #[default]
    Stable,
    Rc,
    Nightly,
}

impl Channel {
    pub(crate) fn label(self) -> std::borrow::Cow<'static, str> {
        match self {
            Self::Stable => rust_i18n::t!("channel.stable"),
            Self::Rc => rust_i18n::t!("channel.rc"),
            Self::Nightly => rust_i18n::t!("channel.nightly"),
        }
    }
}

/// Channel this binary was built for; `None` for dev builds (`cargo build`).
pub(crate) fn built_channel() -> Option<Channel> {
    match env!("ARKE_CHANNEL") {
        "stable" => Some(Channel::Stable),
        "rc" => Some(Channel::Rc),
        "nightly" => Some(Channel::Nightly),
        _ => None,
    }
}

/// One line for the About page: `0.2.0-rc.1 · RC · 1a2b3c4d` (dev builds say so instead).
pub(crate) fn describe() -> String {
    let channel = built_channel().map_or_else(|| rust_i18n::t!("channel.dev"), Channel::label);
    let mut parts = vec![VERSION.to_string(), channel.into_owned()];
    if !COMMIT.is_empty() {
        parts.push(COMMIT.to_string());
    }
    parts.join(" · ")
}

#[cfg(test)]
mod license_tests {
    #[test]
    fn embeds_the_license_texts() {
        let text = super::THIRD_PARTY_LICENSES;
        assert!(text.starts_with("# Third-party licenses"));
        assert!(text.contains("- gpui-pre "), "GPUI is listed");
        assert!(
            text.contains("Apache License"),
            "with the license text itself"
        );
    }
}
