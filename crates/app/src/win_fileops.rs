//! Windows file operations and the file clipboard.
//!
//! - File operations go through `IFileOperation`, Explorer's copy engine, which handles
//!   progress, conflicts, confirmations and the Recycle Bin. Each operation initializes
//!   an STA on the caller's background thread.
//! - The clipboard uses CF_HDROP + "Preferred DropEffect", the format Explorer reads and
//!   writes, so copy/paste works between Arke and Explorer in both directions.
//!
//! Everything here can block (dialogs, clipboard held by another app, network paths), so
//! call only from background threads.

