/// CF_HDROP payload: a DROPFILES header plus a double-NUL-terminated list of wide paths.
pub(crate) fn hdrop_bytes(paths: &[PathBuf]) -> Vec<u8> {
    let header = DROPFILES {
        pFiles: size_of::<DROPFILES>() as u32,
        pt: POINT::default(),
        fNC: false.into(),
        fWide: true.into(),
    };
    // SAFETY: DROPFILES is a #[repr(C)] plain-data struct; reading its bytes is sound.
    let header_bytes = unsafe {
        std::slice::from_raw_parts((&raw const header).cast::<u8>(), size_of::<DROPFILES>())
    };
    let mut bytes = header_bytes.to_vec();
    for path in paths {
        for unit in wide(path.as_os_str()) {
            bytes.extend_from_slice(&unit.to_le_bytes());
        }
    }
    bytes.extend_from_slice(&0u16.to_le_bytes());
    bytes
}

