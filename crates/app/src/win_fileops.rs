    /// Recycle Bin: lists freshly recycled temp files with name, origin, size and deletion
    /// time; purge removes only the given item; restore puts the other back. Only this test's
    /// own temp files are touched; everything else in the bin is read only.
    #[test]
    fn recycle_bin_lists_purges_and_restores_temp_files() {
        // Clear leftovers from earlier failed runs (only this test's temp folders).
        let leftovers: Vec<crate::shell::RecycledItem> = crate::win_recycle::list()
            .unwrap()
            .into_iter()
            .filter(|item| {
                item.from.starts_with(crate::win::long_temp_dir())
                    && item.from.components().any(|c| {
                        c.as_os_str()
                            .to_string_lossy()
                            .starts_with("arke-fileop-test-bin-")
                    })
            })
            .collect();
        let purge = |items: &[crate::shell::RecycledItem]| {
            purge_recycled(items, &crate::shell::OpProgress::default()).map_err(|e| e.to_string())
        };
        assert_eq!(purge(&leftovers), Ok(OpOutcome::Done));

        let sb = Sandbox::new("bin");
        let keep = sb.file(r"gone\keep.txt", "keep me");
        let drop = sb.file(r"gone\drop.txt", "drop");
        let dir = sb.0.join("gone").join("dir");
        sb.file(r"gone\dir\a.bin", "12345");
        run(&FileOp::Delete {
            paths: vec![keep.clone(), drop.clone(), dir.clone()],
            recycle: true,
        });
        assert!(!keep.exists() && !drop.exists() && !dir.exists());

        // The temp path may use 8.3 short names; compare canonical folders.
        let from = fs::canonicalize(sb.0.join("gone")).unwrap();
        let mine = || -> Vec<crate::shell::RecycledItem> {
            let mut items: Vec<_> = crate::win_recycle::list()
                .unwrap()
                .into_iter()
                .filter(|item| fs::canonicalize(&item.from).ok().as_ref() == Some(&from))
                .collect();
            items.sort_by(|a, b| a.name.cmp(&b.name));
            items
        };
        let listed = mine();
        let names: Vec<&str> = listed.iter().map(|item| item.name.as_str()).collect();
        assert_eq!(names, ["dir", "drop.txt", "keep.txt"]);
        let (dir_item, drop_item, keep_item) = (&listed[0], &listed[1], &listed[2]);
        assert!(dir_item.is_dir && !drop_item.is_dir && !keep_item.is_dir);
        assert_eq!(keep_item.size, 7);
        assert_eq!(
            dir_item.size, 5,
            "a folder's size is the sum of its contents"
        );
        let age = std::time::SystemTime::now()
            .duration_since(keep_item.deleted.expect("has a deletion time"))
            .expect("deletion time is not in the future");
        assert!(age < Duration::from_secs(600), "deleted just now: {age:?}");
        for item in &listed {
            assert!(in_recycle_bin(Path::new(&item.now)), "{}", item.now);
        }

        // A place outside the bin rejects the whole batch.
        let bystander = sb.file(r"gone\bystander.txt", "stay");
        let stray = crate::shell::RecycledItem {
            now: bystander.to_str().unwrap().to_owned(),
            ..drop_item.clone()
        };
        assert!(purge(&[drop_item.clone(), stray]).is_err());
        assert!(bystander.exists());
        assert_eq!(mine().len(), 3);

        // Purge one file and one folder, `$R` data and `$I` record; the other item stays.
        let progress = crate::shell::OpProgress::default();
        assert_eq!(
            purge_recycled(&[drop_item.clone(), dir_item.clone()], &progress)
                .map_err(|e| e.to_string()),
            Ok(OpOutcome::Done)
        );
        assert_eq!(progress.work_done.load(Ordering::Relaxed), 2);
        assert_eq!(progress.work_total.load(Ordering::Relaxed), 2);
        let left = mine();
        assert_eq!(left.len(), 1);
        assert_eq!(left[0].name, "keep.txt");
        for gone in [drop_item, dir_item] {
            let data = Path::new(&gone.now);
            let name = data.file_name().unwrap().to_str().unwrap();
            let info = data.with_file_name(format!("$I{}", &name[2..]));
            assert!(!data.exists() && !info.exists(), "{}", gone.now);
        }

        // Restore: back in the original folder, no leftover bin entry.
        let back = Undo::PutBack(vec![PutBack {
            now: keep_item.now.clone(),
            parent: keep_item.from.clone(),
            name: keep_item.name.clone(),
        }]);
        assert_eq!(
            undo(&back, None, true).map_err(|e| e.to_string()),
            Ok(OpOutcome::Done)
        );
        assert_eq!(fs::read_to_string(&keep).unwrap(), "keep me");
        assert!(mine().is_empty());
        assert!(!drop.exists() && !dir.exists());
    }

