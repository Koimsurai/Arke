/// Shell data object, the same kind Explorer puts on the clipboard (CF_HDROP, Shell IDList
/// Array, file names, ...) plus Preferred DropEffect. Needed for Explorer's "Paste shortcut"
/// and apps like Outlook that only accept shell formats. Parsing network paths can block, so
/// call from a background thread with COM initialized.
pub(crate) fn shell_data_object(
    paths: &[PathBuf],
    cut: bool,
) -> Result<windows::Win32::System::Com::IDataObject, ShellError> {
    use std::mem::ManuallyDrop;
    use windows::Win32::System::Com::{
        CoTaskMemFree, DVASPECT_CONTENT, FORMATETC, IDataObject, STGMEDIUM, STGMEDIUM_0,
        TYMED_HGLOBAL,
    };
    use windows::Win32::UI::Shell::Common::ITEMIDLIST;
    use windows::Win32::UI::Shell::{
        BHID_DataObject, IShellItemArray, SHCreateShellItemArrayFromIDLists, SHParseDisplayName,
    };
    /// Parsed PIDLs, freed together.
    struct Pidls(Vec<*mut ITEMIDLIST>);
    impl Drop for Pidls {
        fn drop(&mut self) {
            for pidl in &self.0 {
                // SAFETY: allocated by SHParseDisplayName with CoTaskMemAlloc; freed once each.
                unsafe { CoTaskMemFree(Some(pidl.cast_const().cast())) };
            }
        }
    }
    if paths.is_empty() {
        return Err(ShellError::ClipboardEmpty);
    }
    let mut pidls = Pidls(Vec::with_capacity(paths.len()));
    for path in paths {
        let name = wide(path.as_os_str());
        let mut pidl = std::ptr::null_mut();
        // SAFETY: name is NUL-terminated; pidl is an out variable owned by Pidls on success.
        unsafe { SHParseDisplayName(PCWSTR(name.as_ptr()), None, &raw mut pidl, 0, None) }?;
        pidls.0.push(pidl);
    }
    let list: Vec<*const ITEMIDLIST> = pidls.0.iter().map(|p| p.cast_const()).collect();
    // SAFETY: the PIDLs in list stay alive (Pidls) for the call; the array and data object
    // keep their own copies.
    let object: IDataObject = unsafe {
        let array: IShellItemArray = SHCreateShellItemArrayFromIDLists(&list)?;
        array.BindToHandler(None, &BHID_DataObject)?
    };
    // Explorer uses COPY|LINK for copy and MOVE for cut.
    let effect = if cut {
        DROPEFFECT_MOVE
    } else {
        DROPEFFECT_COPY | DROPEFFECT_LINK
    };
    let mut mem = Global::new(&effect.to_le_bytes())?;
    let Some(handle) = mem.handle() else {
        return Err(ShellError::GlobalMemory);
    };
    let format = FORMATETC {
        cfFormat: u16::try_from(drop_effect_format()).unwrap_or_default(),
        ptd: std::ptr::null_mut(),
        dwAspect: DVASPECT_CONTENT.0,
        lindex: -1,
        tymed: TYMED_HGLOBAL.0.cast_unsigned(),
    };
    let medium = STGMEDIUM {
        tymed: TYMED_HGLOBAL.0.cast_unsigned(),
        u: STGMEDIUM_0 {
            hGlobal: HGLOBAL(handle.0),
        },
        pUnkForRelease: ManuallyDrop::new(None),
    };
    // SAFETY: format and medium are valid for the call; with fRelease = true the data object
    // owns the memory on success.
    unsafe {
        object.SetData(
            std::ptr::from_ref(&format),
            std::ptr::from_ref(&medium),
            true,
        )
    }?;
    mem.release();
    Ok(object)
}

/// Puts a shell data object on the clipboard and flushes it (`OleFlushClipboard`) so the
/// data no longer depends on this thread or object staying alive.
fn set_clipboard_shell(files: &ClipboardFiles) -> Result<(), ShellError> {
    use windows::Win32::System::Ole::{
        OleFlushClipboard, OleInitialize, OleSetClipboard, OleUninitialize,
    };
    // SAFETY: OLE init on this background thread, paired with OleUninitialize only on success.
    unsafe { OleInitialize(None) }?;
    let result = (|| {
        let object = shell_data_object(&files.paths, files.cut)?;
        // SAFETY: object is a valid data object; OLE is initialized on this thread.
        unsafe {
            OleSetClipboard(&object)?;
            OleFlushClipboard().map_err(ShellError::from)
        }
    })();
    // SAFETY: pairs with the successful OleInitialize above.
    unsafe { OleUninitialize() };
    result
}

pub(crate) fn set_clipboard_files(files: &ClipboardFiles) -> Result<u32, ShellError> {
    // Prefer the shell data object (most formats); if e.g. a path can't be parsed, fall back
    // to a hand-built CF_HDROP.
    match set_clipboard_shell(files) {
        // SAFETY: only reads the sequence number.
        Ok(()) => return Ok(unsafe { GetClipboardSequenceNumber() }),
        Err(err) => log::info!("clipboard falling back to CF_HDROP: {err}"),
    }
    let mut hdrop = Global::new(&hdrop_bytes(&files.paths))?;
    // Explorer uses COPY|LINK for copy and MOVE for cut.
    let effect = if files.cut {
        DROPEFFECT_MOVE
    } else {
        DROPEFFECT_COPY | DROPEFFECT_LINK
    };
    let mut effect_mem = Global::new(&effect.to_le_bytes())?;
    let window = MessageWindow::new()?;
    {
        let _clipboard = OpenedClipboard::open(Some(window.0))?;
        // SAFETY: the clipboard is open on this thread; after SetClipboardData succeeds the
        // system owns the memory, hence release.
        unsafe {
            EmptyClipboard()?;
            SetClipboardData(u32::from(CF_HDROP.0), hdrop.handle())?;
            hdrop.release();
            if SetClipboardData(drop_effect_format(), effect_mem.handle()).is_ok() {
                effect_mem.release();
            }
        }
    }
    // SAFETY: only reads the sequence number.
    Ok(unsafe { GetClipboardSequenceNumber() })
}

pub(crate) fn set_clipboard_text(text: &str) -> Result<(), ShellError> {
    let units: Vec<u16> = text.encode_utf16().chain(std::iter::once(0)).collect();
    let bytes: Vec<u8> = units.iter().flat_map(|u| u.to_le_bytes()).collect();
    let mut mem = Global::new(&bytes)?;
    let window = MessageWindow::new()?;
    let _clipboard = OpenedClipboard::open(Some(window.0))?;
    // SAFETY: the clipboard is open on this thread; the system owns the memory on success.
    unsafe {
        EmptyClipboard()?;
        SetClipboardData(u32::from(CF_UNICODETEXT.0), mem.handle())?;
    }
    mem.release();
    Ok(())
}

pub(crate) fn clipboard_files() -> Result<Option<(ClipboardFiles, u32)>, ShellError> {
    // SAFETY: only queries the sequence number and format; the clipboard isn't opened.
    let (seq, available) = unsafe {
        (
            GetClipboardSequenceNumber(),
            IsClipboardFormatAvailable(u32::from(CF_HDROP.0)).is_ok(),
        )
    };
    if !available {
        return Ok(None);
    }
    let _clipboard = OpenedClipboard::open(None)?;
    // SAFETY: the clipboard is open; the handles belong to the clipboard and are only read
    // before it closes, never freed.
    unsafe {
        let Ok(handle) = GetClipboardData(u32::from(CF_HDROP.0)) else {
            return Ok(None);
        };
        let paths = parse_hdrop(HDROP(handle.0));
        let cut = GetClipboardData(drop_effect_format())
            .ok()
            .and_then(|h| {
                let mem = HGLOBAL(h.0);
                let ptr = GlobalLock(mem).cast::<u32>();
                if ptr.is_null() {
                    return None;
                }
                let value = ptr.read_unaligned();
                let _ = GlobalUnlock(mem);
                Some(value)
            })
            .is_some_and(|effect| effect & DROPEFFECT_MOVE != 0);
        Ok((!paths.is_empty()).then_some((ClipboardFiles { paths, cut }, seq)))
    }
}

pub(crate) fn clear_clipboard_if(seq: u32) {
    // SAFETY: only reads the sequence number. Clear only if unchanged, so content copied
    // later is kept.
    if unsafe { GetClipboardSequenceNumber() } != seq {
        return;
    }
    if let Ok(_clipboard) = OpenedClipboard::open(None) {
        // SAFETY: the clipboard is open.
        let _ = unsafe { EmptyClipboard() };
    }
}

pub(crate) fn clipboard_seq() -> u32 {
    // SAFETY: only reads the sequence number; non-blocking.
    unsafe { GetClipboardSequenceNumber() }
}

pub(crate) fn clipboard_has_files() -> bool {
    // SAFETY: only checks format availability; non-blocking.
    unsafe { IsClipboardFormatAvailable(u32::from(CF_HDROP.0)) }.is_ok()
}

