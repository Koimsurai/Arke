/// Progress sink for the copy engine. Records the actual result of each item so the
/// operation can be undone. Code generated by `#[implement]` trips two pedantic lints,
/// so they are allowed for this module.
#[allow(clippy::ref_as_ptr, clippy::inline_always)]
mod recorder {
    use super::{
        HRESULT, IFileOperationProgressSink, IFileOperationProgressSink_Impl, IShellItem, PCWSTR,
        PathBuf, SIGDN, SIGDN_DESKTOPABSOLUTEPARSING, SIGDN_FILESYSPATH,
    };

    #[windows::core::implement(IFileOperationProgressSink)]
    pub(super) struct Recorder {
        pub(super) done: std::cell::RefCell<Vec<Done>>,
        /// Set when Arke draws its own progress: progress goes here, cancel is read here.
        pub(super) progress: Option<std::sync::Arc<crate::shell::OpProgress>>,
        /// Failed items (path when known, display name, reason), reported together when Windows
        /// shows no error UI.
        pub(super) failed: std::cell::RefCell<Vec<(Option<PathBuf>, String, HRESULT)>>,
    }

    /// One completed item.
    pub(super) enum Done {
        /// Moved, renamed or recycled from `from` to `now`.
        Relocated { from: PathBuf, now: String },
        /// Newly created (copied or new item).
        Created(PathBuf),
    }

    /// Display name of the item (`SIGDN_*`).
    fn item_name(item: &IShellItem, kind: SIGDN) -> Option<String> {
        // SAFETY: item is a valid interface; the returned string is copied, then freed with
        // CoTaskMemFree.
        unsafe {
            let p = item.GetDisplayName(kind).ok()?;
            let name = p.to_string().ok();
            windows::Win32::System::Com::CoTaskMemFree(Some(p.0 as *const _));
            name
        }
    }

    fn item_path(item: &IShellItem) -> Option<PathBuf> {
        item_name(item, SIGDN_FILESYSPATH).map(PathBuf::from)
    }

    impl Recorder {
        /// Called before each item. Returning an error after cancel makes Windows stop this
        /// item and all remaining ones.
        fn gate(&self) -> windows::core::Result<()> {
            use std::sync::atomic::Ordering;
            match &self.progress {
                Some(p) if p.cancel.load(Ordering::Relaxed) => Err(windows::core::Error::from(
                    windows::Win32::Foundation::ERROR_CANCELLED.to_hresult(),
                )),
                _ => Ok(()),
            }
        }

        /// Records a failed item. Missing items and cancellations don't count.
        fn check(&self, hr: HRESULT, item: Option<&IShellItem>) {
            if hr.is_ok() || super::is_gone(hr) || super::is_cancel(hr) {
                return;
            }
            let name = item
                .and_then(|i| item_name(i, windows::Win32::UI::Shell::SIGDN_NORMALDISPLAY))
                .unwrap_or_default();
            self.failed
                .borrow_mut()
                .push((item.and_then(item_path), name, hr));
        }

        fn tick(&self) {
            if let Some(p) = &self.progress {
                p.done.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
            }
        }

        fn relocated(&self, hr: HRESULT, item: Option<&IShellItem>, now: Option<&IShellItem>) {
            let (Some(item), Some(now)) = (item, now) else {
                return;
            };
            if hr.is_err() {
                return;
            }
            // File system path when there is one; for Recycle Bin items, the parsing name
            // used later to restore them.
            let now_name = item_path(now).map_or_else(
                || item_name(now, SIGDN_DESKTOPABSOLUTEPARSING),
                |p| Some(p.to_string_lossy().into_owned()),
            );
            if let (Some(from), Some(now)) = (item_path(item), now_name) {
                self.done.borrow_mut().push(Done::Relocated { from, now });
            }
        }

        /// Adds the file size after a copy or cross-volume move, for the speed readout.
        /// Same-volume moves are renames and don't count.
        fn add_bytes(
            &self,
            hr: HRESULT,
            item: Option<&IShellItem>,
            now: Option<&IShellItem>,
            is_move: bool,
        ) {
            if hr.is_err() {
                return;
            }
            let (Some(p), Some(path)) = (&self.progress, now.and_then(item_path)) else {
                return;
            };
            if is_move {
                let drive = |p: &std::path::Path| {
                    p.components()
                        .next()
                        .map(|c| c.as_os_str().to_ascii_lowercase())
                };
                if item
                    .and_then(item_path)
                    .is_some_and(|from| drive(&from) == drive(&path))
                {
                    return;
                }
            }
            if let Ok(meta) = std::fs::metadata(&path)
                && meta.is_file()
            {
                p.bytes
                    .fetch_add(meta.len(), std::sync::atomic::Ordering::Relaxed);
            }
        }

        fn created(&self, hr: HRESULT, now: Option<&IShellItem>) {
            if hr.is_err() {
                return;
            }
            if let Some(path) = now.and_then(item_path) {
                self.done.borrow_mut().push(Done::Created(path));
            }
        }
    }

    #[allow(non_snake_case)]
    impl IFileOperationProgressSink_Impl for Recorder_Impl {
        fn StartOperations(&self) -> windows::core::Result<()> {
            Ok(())
        }
        fn FinishOperations(&self, _: HRESULT) -> windows::core::Result<()> {
            Ok(())
        }
        fn PreRenameItem(
            &self,
            _: u32,
            _: windows::core::Ref<IShellItem>,
            _: &PCWSTR,
        ) -> windows::core::Result<()> {
            self.gate()
        }
        fn PostRenameItem(
            &self,
            _: u32,
            item: windows::core::Ref<IShellItem>,
            _: &PCWSTR,
            hr: HRESULT,
            now: windows::core::Ref<IShellItem>,
        ) -> windows::core::Result<()> {
            self.tick();
            self.check(hr, item.as_ref());
            self.relocated(hr, item.as_ref(), now.as_ref());
            Ok(())
        }
        fn PreMoveItem(
            &self,
            _: u32,
            _: windows::core::Ref<IShellItem>,
            _: windows::core::Ref<IShellItem>,
            _: &PCWSTR,
        ) -> windows::core::Result<()> {
            self.gate()
        }
        fn PostMoveItem(
            &self,
            _: u32,
            item: windows::core::Ref<IShellItem>,
            _: windows::core::Ref<IShellItem>,
            _: &PCWSTR,
            hr: HRESULT,
            now: windows::core::Ref<IShellItem>,
        ) -> windows::core::Result<()> {
            self.tick();
            self.check(hr, item.as_ref());
            self.add_bytes(hr, item.as_ref(), now.as_ref(), true);
            self.relocated(hr, item.as_ref(), now.as_ref());
            Ok(())
        }
        fn PreCopyItem(
            &self,
            _: u32,
            _: windows::core::Ref<IShellItem>,
            _: windows::core::Ref<IShellItem>,
            _: &PCWSTR,
        ) -> windows::core::Result<()> {
            self.gate()
        }
        fn PostCopyItem(
            &self,
            _: u32,
            item: windows::core::Ref<IShellItem>,
            _: windows::core::Ref<IShellItem>,
            _: &PCWSTR,
            hr: HRESULT,
            now: windows::core::Ref<IShellItem>,
        ) -> windows::core::Result<()> {
            self.tick();
            self.check(hr, item.as_ref());
            self.add_bytes(hr, item.as_ref(), now.as_ref(), false);
            self.created(hr, now.as_ref());
            Ok(())
        }
        fn PreDeleteItem(
            &self,
            _: u32,
            _: windows::core::Ref<IShellItem>,
        ) -> windows::core::Result<()> {
            self.gate()
        }
        fn PostDeleteItem(
            &self,
            _: u32,
            item: windows::core::Ref<IShellItem>,
            hr: HRESULT,
            now: windows::core::Ref<IShellItem>,
        ) -> windows::core::Result<()> {
            self.tick();
            self.check(hr, item.as_ref());
            // When recycling, `now` is the item in the Recycle Bin; for permanent deletes it
            // is null and nothing is recorded.
            self.relocated(hr, item.as_ref(), now.as_ref());
            Ok(())
        }
        fn PreNewItem(
            &self,
            _: u32,
            _: windows::core::Ref<IShellItem>,
            _: &PCWSTR,
        ) -> windows::core::Result<()> {
            self.gate()
        }
        fn PostNewItem(
            &self,
            _: u32,
            _: windows::core::Ref<IShellItem>,
            _: &PCWSTR,
            _: &PCWSTR,
            _: u32,
            hr: HRESULT,
            now: windows::core::Ref<IShellItem>,
        ) -> windows::core::Result<()> {
            self.tick();
            self.created(hr, now.as_ref());
            Ok(())
        }
        fn UpdateProgress(&self, total: u32, so_far: u32) -> windows::core::Result<()> {
            if let Some(p) = &self.progress {
                use std::sync::atomic::Ordering;
                p.work_total.store(u64::from(total), Ordering::Relaxed);
                p.work_done.store(u64::from(so_far), Ordering::Relaxed);
            }
            Ok(())
        }
        fn ResetTimer(&self) -> windows::core::Result<()> {
            Ok(())
        }
        fn PauseTimer(&self) -> windows::core::Result<()> {
            Ok(())
        }
        fn ResumeTimer(&self) -> windows::core::Result<()> {
            Ok(())
        }
    }
}

use recorder::{Done, Recorder};

/// Item already gone (e.g. a link target deleted earlier in the batch); treated as done.
fn is_gone(hr: HRESULT) -> bool {
    use windows::Win32::Foundation::{ERROR_FILE_NOT_FOUND, ERROR_PATH_NOT_FOUND};
    hr == ERROR_FILE_NOT_FOUND.to_hresult() || hr == ERROR_PATH_NOT_FOUND.to_hresult()
}

fn is_cancel(hr: HRESULT) -> bool {
    hr == ERROR_CANCELLED.to_hresult() || hr == COPYENGINE_E_USER_CANCELLED
}

/// Turns the copy engine's per-item failures into reports, by path when it gave one.
fn failures(failed: Vec<(Option<PathBuf>, String, HRESULT)>) -> Vec<ItemFailure> {
    failed
        .into_iter()
        .map(|(path, name, hr)| {
            ItemFailure::new(
                path.unwrap_or_else(|| PathBuf::from(name)),
                arke_core::failure::from_hresult(hr.0),
                message(&windows::core::Error::from(hr)),
            )
        })
        .collect()
}

/// Items looked up at most for programs holding them, so a big failed batch reports quickly.
const EXPLAIN_MAX: usize = 3;

/// Adds which programs hold the first few items that failed because they were in use, so the
/// report can say "in use by Word (PID 1234)". An "access denied" item that turns out to be held
/// by a program (a running .exe, a file mapped into memory) is reported as in use: closing that
/// program is what fixes it. Background thread.
pub(crate) fn explain(failed: &mut [ItemFailure]) {
    use arke_core::failure::FailReason;
    for failure in failed
        .iter_mut()
        .filter(|f| matches!(f.reason, FailReason::InUse | FailReason::AccessDenied))
        .take(EXPLAIN_MAX)
    {
        failure.holders = crate::win_inuse::holders(&failure.path);
        if !failure.holders.is_empty() {
            failure.reason = FailReason::InUse;
        }
    }
}

/// Turns completed items into undo steps.
fn undo_from(done: Vec<Done>) -> Option<Undo> {
    if done.is_empty() {
        return None;
    }
    if done.iter().all(|d| matches!(d, Done::Created(_))) {
        return Some(Undo::Remove(
            done.into_iter()
                .filter_map(|d| match d {
                    Done::Created(p) => Some(p),
                    Done::Relocated { .. } => None,
                })
                .collect(),
        ));
    }
    let items: Vec<PutBack> = done
        .into_iter()
        .filter_map(|d| match d {
            Done::Relocated { from, now } => Some(PutBack {
                now,
                parent: from.parent()?.to_path_buf(),
                name: from.file_name()?.to_string_lossy().into_owned(),
            }),
            Done::Created(_) => None,
        })
        .collect();
    (!items.is_empty()).then_some(Undo::PutBack(items))
}

/// Runs a file operation. `silent` suppresses all dialogs, including the permanent
/// delete confirmation; tests only.
pub(crate) fn perform(
    op: &FileOp,
    owner: Option<isize>,
    silent: bool,
) -> Result<OpOutcome, ShellError> {
    perform_undoable(op, owner, silent).0
}

/// Runs a file operation and records how to undo it.
pub(crate) fn perform_undoable(
    op: &FileOp,
    owner: Option<isize>,
    silent: bool,
) -> (Result<OpOutcome, ShellError>, Option<Undo>) {
    perform_recorded(op, owner, silent, None)
}

thread_local! {
    /// Hide Windows' progress window for the operation on this thread; Arke draws its own.
    static HIDE_PROGRESS: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
}

/// Runs a file operation with progress reported to `progress` instead of Windows'
/// progress window. Confirmations and conflicts still use Windows' dialogs.
pub(crate) fn perform_tracked(
    op: &FileOp,
    owner: Option<isize>,
    progress: &std::sync::Arc<crate::shell::OpProgress>,
) -> (Result<OpOutcome, ShellError>, Option<Undo>) {
    // Permanent deletes are done by Arke (no Windows error UI, links removed without touching
    // their targets; see win_purge.rs). Nothing to undo.
    if let FileOp::Delete {
        paths,
        recycle: false,
    } = op
    {
        return (crate::win_purge::purge(paths, progress), None);
    }
    HIDE_PROGRESS.set(true);
    let outcome = perform_recorded(op, owner, false, Some(progress.clone()));
    HIDE_PROGRESS.set(false);
    outcome
}

fn perform_recorded(
    op: &FileOp,
    owner: Option<isize>,
    silent: bool,
    progress: Option<std::sync::Arc<crate::shell::OpProgress>>,
) -> (Result<OpOutcome, ShellError>, Option<Undo>) {
    let recycled = match op {
        FileOp::Delete {
            paths,
            recycle: true,
        } => Some(paths.as_slice()),
        _ => None,
    };
    let shorts = recycled.map(short_forms).unwrap_or_default();
    let cancel = progress.clone();
    let recorder: IFileOperationProgressSink = Recorder {
        done: std::cell::RefCell::new(Vec::new()),
        progress,
        failed: std::cell::RefCell::new(Vec::new()),
    }
    .into();
    let mut failed = Vec::new();
    let result = run(op, owner, silent, Some(&recorder), &mut failed);
    // SAFETY: recorder wraps the Recorder created above on this thread; as_impl returns it.
    let sink = unsafe { windows::core::AsImpl::<Recorder>::as_impl(&recorder) };
    let mut done = sink.done.take();
    failed.extend(failures(sink.failed.take()));
    if let Some(paths) = recycled {
        long_names_back(&shorts, &mut done);
        let cancelled = cancel.is_some_and(|p| p.cancel.load(std::sync::atomic::Ordering::Relaxed));
        if matches!(result, Ok(OpOutcome::Cancelled)) && !cancelled {
            bad_names_inside(paths, &done, &mut failed);
        }
    }
    explain(&mut failed);
    // With Arke's own progress there is no error UI (FOF_NOERRORUI); report failures at the end.
    let result = match result {
        Ok(_) if !failed.is_empty() => Err(ShellError::Items { failed }),
        other => other,
    };
    (result, undo_from(done))
}

/// A recycled item's key for [`long_names_back`]: its folder in long form plus its own name, both
/// lowercased. The folder still exists after the item is gone, so it can be expanded, and any mix of
/// short and long folder names (a temp folder like `RUNNER~1`) compares equal.
fn recycled_key(folder: &Path, name: &std::ffi::OsStr) -> (String, String) {
    (
        long_form(folder).to_string_lossy().to_lowercase(),
        name.to_string_lossy().to_lowercase(),
    )
}

/// `path` with every 8.3 component expanded, or as given when that fails.
fn long_form(path: &Path) -> PathBuf {
    use windows::Win32::Storage::FileSystem::GetLongPathNameW;
    let wide = windows::core::HSTRING::from(arke_core::path::verbatim(path).as_os_str());
    let mut buf = vec![0u16; 32_768];
    // SAFETY: `wide` is NUL-terminated and buf is writable for its whole length.
    let len = unsafe { GetLongPathNameW(&wide, Some(&mut buf)) } as usize;
    if len == 0 || len >= buf.len() {
        return path.to_path_buf();
    }
    arke_core::path::unverbatim(&PathBuf::from(String::from_utf16_lossy(&buf[..len])))
}

/// Short (8.3) names of items whose paths are over 260 characters, which the copy engine reports
/// recycled items by. Mapped back with [`long_names_back`] so undo restores the real names.
fn short_forms(paths: &[PathBuf]) -> Vec<((String, String), PathBuf)> {
    use windows::Win32::Storage::FileSystem::GetShortPathNameW;
    const MAX_PATH: usize = 260;
    paths
        .iter()
        .filter(|p| p.as_os_str().len() >= MAX_PATH)
        .filter_map(|path| {
            let folder = path.parent()?;
            let long = windows::core::HSTRING::from(arke_core::path::verbatim(path).as_os_str());
            let mut buf = vec![0u16; 32_768];
            // SAFETY: `long` is NUL-terminated and buf is writable for its whole length.
            let len = unsafe { GetShortPathNameW(&long, Some(&mut buf)) } as usize;
            if len == 0 || len >= buf.len() {
                return None;
            }
            let short = PathBuf::from(String::from_utf16_lossy(&buf[..len]));
            let name = short.file_name()?.to_os_string();
            Some((recycled_key(folder, &name), path.clone()))
        })
        .collect()
}

/// Replaces short (8.3) origins of recycled items with the paths that were asked for.
fn long_names_back(shorts: &[((String, String), PathBuf)], done: &mut [Done]) {
    if shorts.is_empty() {
        return;
    }
    for item in done {
        if let Done::Relocated { from, .. } = item {
            let from_plain = arke_core::path::unverbatim(from);
            let (Some(folder), Some(name)) = (from_plain.parent(), from_plain.file_name()) else {
                continue;
            };
            let key = recycled_key(folder, name);
            if let Some((_, long)) = shorts.iter().find(|(short, _)| *short == key) {
                from.clone_from(long);
            }
        }
    }
}

/// Entries looked at, at most, when finding out why a folder couldn't be recycled.
const SCAN_MAX: usize = 20_000;

/// The copy engine gives up on a folder holding names it can't handle (`x.`, `con`) and reports
/// the whole operation as cancelled, with no error. When the user didn't cancel, finds such
/// folders among those not recycled so the report says why.
fn bad_names_inside(paths: &[PathBuf], done: &[Done], failed: &mut Vec<ItemFailure>) {
    for path in paths {
        let recycled = done
            .iter()
            .any(|d| matches!(d, Done::Relocated { from, .. } if from == path));
        if recycled || failed.iter().any(|f| f.path == *path) {
            continue;
        }
        if holds_bad_name(&arke_core::path::verbatim(path)) {
            failed.push(ItemFailure::new(
                path.clone(),
                arke_core::failure::FailReason::BadNameInside,
                String::new(),
            ));
        }
    }
}

/// Whether the folder at `root` (a `\\?\` path) holds an item the shell can't handle.
fn holds_bad_name(root: &Path) -> bool {
    let mut dirs = vec![root.to_path_buf()];
    let mut seen = 0usize;
    while let Some(dir) = dirs.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            seen += 1;
            if seen > SCAN_MAX {
                return false;
            }
            if entry
                .file_name()
                .to_str()
                .is_some_and(arke_core::path::shell_unsafe_name)
            {
                return true;
            }
            if entry
                .file_type()
                .is_ok_and(|t| t.is_dir() && !t.is_symlink())
            {
                dirs.push(entry.path());
            }
        }
    }
    false
}

/// Why a path to delete couldn't even be handed to the copy engine; `None` when it is already
/// gone (deleted meanwhile, which counts as done).
fn unqueued(path: &Path, error: &windows::core::Error) -> Option<ItemFailure> {
    use arke_core::failure::FailReason;
    if std::fs::symlink_metadata(arke_core::path::verbatim(path))
        .is_err_and(|e| e.kind() == std::io::ErrorKind::NotFound)
    {
        return None;
    }
    let reason = arke_core::failure::from_hresult(error.code().0);
    // It exists, so "not found" or "bad device" means the shell can't parse its name.
    let bad_name = path
        .file_name()
        .and_then(|n| n.to_str())
        .is_some_and(arke_core::path::shell_unsafe_name)
        || reason == FailReason::Gone
        || error.code() == windows::Win32::Foundation::ERROR_BAD_DEVICE.to_hresult()
        || error.code() == windows::Win32::Foundation::ERROR_INVALID_NAME.to_hresult();
    Some(ItemFailure::new(
        path.to_path_buf(),
        if bad_name {
            FailReason::BadName
        } else {
            reason
        },
        message(error),
    ))
}

/// Undoes an operation: moves items back, or recycles newly created ones.
pub(crate) fn undo(
    undo: &Undo,
    owner: Option<isize>,
    silent: bool,
) -> Result<OpOutcome, ShellError> {
    undo_with(undo, owner, silent, None)
}

/// Undo with progress shown in Arke instead of Windows' progress window.
pub(crate) fn undo_tracked(
    undo: &Undo,
    owner: Option<isize>,
    progress: &std::sync::Arc<crate::shell::OpProgress>,
) -> Result<OpOutcome, ShellError> {
    let recorder: IFileOperationProgressSink = Recorder {
        done: std::cell::RefCell::new(Vec::new()),
        progress: Some(progress.clone()),
        failed: std::cell::RefCell::new(Vec::new()),
    }
    .into();
    HIDE_PROGRESS.set(true);
    let result = undo_with(undo, owner, false, Some(&recorder));
    HIDE_PROGRESS.set(false);
    result
}

fn undo_with(
    undo: &Undo,
    owner: Option<isize>,
    silent: bool,
    sink: Option<&IFileOperationProgressSink>,
) -> Result<OpOutcome, ShellError> {
    match undo {
        // Created items already gone count as undone.
        Undo::Remove(paths) => run(
            &FileOp::Delete {
                paths: paths.clone(),
                recycle: true,
            },
            owner,
            silent,
            sink,
            &mut Vec::new(),
        ),
        Undo::PutBack(items) => {
            let _com = Com::init()?;
            // SAFETY: COM is initialized on this thread; arguments are valid interfaces or
            // live wide strings.
            let result = unsafe {
                let fo: IFileOperation = CoCreateInstance(&FileOperation, None, CLSCTX_ALL)?;
                for item in items {
                    let w = wide(std::ffi::OsStr::new(&item.now));
                    let now =
                        SHCreateItemFromParsingName::<_, _, IShellItem>(PCWSTR(w.as_ptr()), None)
                            .map_err(|_| ShellError::Missing {
                            name: item.name.clone(),
                        })?;
                    let name = wide(std::ffi::OsStr::new(&item.name));
                    fo.MoveItem(
                        &now,
                        &shell_item(&item.parent)?,
                        PCWSTR(name.as_ptr()),
                        None,
                    )?;
                }
                let cookie = sink.and_then(|sink| fo.Advise(sink).ok());
                let result = finish(&fo, FILEOPERATION_FLAGS(0), owner, silent);
                if let Some(cookie) = cookie {
                    let _ = fo.Unadvise(cookie);
                }
                result
            };
            forget_recycled(items.iter().map(|item| item.now.as_str()));
            result
        }
    }
}

/// Whether `path` is a top-level Recycle Bin item, `X:/$Recycle.Bin/<SID>/$R...`. Neither
/// the bin folder itself nor anything nested inside an item matches.
pub(crate) fn in_recycle_bin(path: &Path) -> bool {
    use std::path::Component;
    let mut parts = path.components();
    matches!(parts.next(), Some(Component::Prefix(_)))
        && matches!(parts.next(), Some(Component::RootDir))
        && parts
            .next()
            .is_some_and(|c| c.as_os_str().eq_ignore_ascii_case("$Recycle.Bin"))
        && matches!(parts.next(), Some(Component::Normal(_)))
        && parts.next().is_some_and(|c| {
            c.as_os_str()
                .to_str()
                .is_some_and(|name| name.starts_with("$R") && name.len() > 2)
        })
        && parts.next().is_none()
}

/// Permanently deletes Recycle Bin items at `places`, with no confirmation or progress UI
/// (Arke has already asked). If any place is outside the Recycle Bin, the whole batch is
/// rejected and nothing is deleted.
pub(crate) fn purge_recycled(
    places: &[&str],
    owner: Option<isize>,
) -> Result<OpOutcome, ShellError> {
    if let Some(stray) = places.iter().find(|now| !in_recycle_bin(Path::new(now))) {
        return Err(ShellError::Missing {
            name: (*stray).to_owned(),
        });
    }
    let _com = Com::init()?;
    // SAFETY: COM is initialized on this thread; arguments are valid interfaces.
    let result = unsafe {
        let fo: IFileOperation = CoCreateInstance(&FileOperation, None, CLSCTX_ALL)?;
        let mut queued = 0usize;
        for now in places {
            // Already gone (emptied by another program): skip.
            let Ok(item) = shell_item(Path::new(now)) else {
                continue;
            };
            fo.DeleteItem(&item, None)?;
            queued += 1;
        }
        if queued == 0 {
            Ok(OpOutcome::Done)
        } else {
            finish(&fo, FOF_NOCONFIRMATION | FOF_SILENT, owner, false)
        }
    };
    forget_recycled(places.iter().copied());
    result
}

/// After items leave the Recycle Bin, removes the matching `$I...` metadata files (paired
/// with `$R...`) so the bin doesn't keep empty entries. Touches only those `$I` files.
fn forget_recycled<'a>(places: impl Iterator<Item = &'a str>) {
    for now in places {
        let now = Path::new(now);
        // Keep the metadata for items still in the bin (move or delete failed).
        if !in_recycle_bin(now) || now.exists() {
            continue;
        }
        let Some(name) = now.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        let info = now.with_file_name(format!("$I{}", &name[2..]));
        if info.is_file() {
            let _ = std::fs::remove_file(info);
        }
    }
}

/// Runs `op` through the copy engine. Items to delete that the engine can't even take (their
/// names, say) go to `skipped` while the rest still run; items already gone are left out.
fn run(
    op: &FileOp,
    owner: Option<isize>,
    silent: bool,
    sink: Option<&IFileOperationProgressSink>,
    skipped: &mut Vec<ItemFailure>,
) -> Result<OpOutcome, ShellError> {
    let _com = Com::init()?;
    // SAFETY: COM is initialized on this thread.
    let fo: IFileOperation = unsafe { CoCreateInstance(&FileOperation, None, CLSCTX_ALL) }?;
    let mut flags = if silent {
        FOF_NO_UI
    } else {
        FILEOPERATION_FLAGS(0)
    };
    // SAFETY: IFileOperation arguments below are valid interfaces or wide strings that outlive
    // the calls; per-item sinks are always None.
    unsafe {
        match op {
            FileOp::Copy { sources, dest } | FileOp::Move { sources, dest } => {
                let dest_item = shell_item(dest)?;
                let is_copy = matches!(op, FileOp::Copy { .. });
                // Copying into the same folder auto-renames to "... - Copy" like Explorer
                // instead of asking to replace.
                if is_copy && sources.iter().any(|s| s.parent() == Some(dest.as_path())) {
                    flags |= FOF_RENAMEONCOLLISION;
                }
                for src in sources {
                    let item = shell_item(src)?;
                    if is_copy {
                        fo.CopyItem(&item, &dest_item, PCWSTR::null(), None)
                    } else {
                        fo.MoveItem(&item, &dest_item, PCWSTR::null(), None)
                    }?;
                }
            }
            FileOp::Delete { paths, recycle } => {
                if *recycle {
                    flags |= FOF_ALLOWUNDO | FOFX_RECYCLEONDELETE;
                } else {
                    // Arke has already confirmed the permanent delete.
                    flags |= FOF_NOCONFIRMATION;
                }
                let mut queued = 0usize;
                for path in paths {
                    let w = wide(path.as_os_str());
                    match SHCreateItemFromParsingName::<_, _, IShellItem>(PCWSTR(w.as_ptr()), None)
                    {
                        Ok(item) => {
                            fo.DeleteItem(&item, None)?;
                            queued += 1;
                        }
                        Err(error) => skipped.extend(unqueued(path, &error)),
                    }
                }
                if queued == 0 {
                    return Ok(OpOutcome::Done);
                }
            }
            FileOp::Rename { path, new_name } => {
                let name = wide(std::ffi::OsStr::new(new_name));
                fo.RenameItem(&shell_item(path)?, PCWSTR(name.as_ptr()), None)?;
            }
            FileOp::RenameMany { items } => {
                for (path, new_name) in items {
                    let name = wide(std::ffi::OsStr::new(new_name));
                    fo.RenameItem(&shell_item(path)?, PCWSTR(name.as_ptr()), None)?;
                }
            }
            FileOp::NewFolder { parent, name } => {
                let name = wide(std::ffi::OsStr::new(name));
                fo.NewItem(
                    &shell_item(parent)?,
                    FILE_ATTRIBUTE_DIRECTORY.0,
                    PCWSTR(name.as_ptr()),
                    PCWSTR::null(),
                    None,
                )?;
            }
            FileOp::NewFile { parent, name } => {
                let name = wide(std::ffi::OsStr::new(name));
                fo.NewItem(
                    &shell_item(parent)?,
                    FILE_ATTRIBUTE_NORMAL.0,
                    PCWSTR(name.as_ptr()),
                    PCWSTR::null(),
                    None,
                )?;
            }
        }
        let cookie = sink.and_then(|sink| fo.Advise(sink).ok());
        let result = finish(&fo, flags, owner, silent);
        if let Some(cookie) = cookie {
            let _ = fo.Unadvise(cookie);
        }
        result
    }
}

/// Sets flags and owner window, performs the operations and maps the result.
///
/// # Safety
/// COM must be initialized on this thread and `fo` created on it.
unsafe fn finish(
    fo: &IFileOperation,
    flags: FILEOPERATION_FLAGS,
    owner: Option<isize>,
    silent: bool,
) -> Result<OpOutcome, ShellError> {
    let flags = if silent { flags | FOF_NO_UI } else { flags };
    // With Arke's own progress: no progress window (FOF_SILENT) and no error UI
    // (FOF_NOERRORUI; failures are skipped and reported at the end). Confirmations remain.
    let flags = if HIDE_PROGRESS.get() {
        flags | windows::Win32::UI::Shell::FOF_SILENT | windows::Win32::UI::Shell::FOF_NOERRORUI
    } else {
        flags
    };
    // SAFETY: guaranteed by the caller, see `# Safety`.
    unsafe {
        fo.SetOperationFlags(flags)?;
        if let (Some(hwnd), false) = (owner, silent) {
            // Parent dialogs to the Arke window; failure doesn't affect the operation.
            let _ = fo.SetOwnerWindow(HWND(hwnd as *mut _));
        }
        let result = fo.PerformOperations();
        let aborted = fo
            .GetAnyOperationsAborted()
            .is_ok_and(windows::core::BOOL::as_bool);
        match result {
            Ok(()) if aborted => Ok(OpOutcome::Cancelled),
            Ok(()) => Ok(OpOutcome::Done),
            Err(e)
                if e.code() == ERROR_CANCELLED.to_hresult()
                    || e.code() == COPYENGINE_E_USER_CANCELLED =>
            {
                Ok(OpOutcome::Cancelled)
            }
            Err(e) => Err(e.into()),
        }
    }
}

