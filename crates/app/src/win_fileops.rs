/// Drags files out to other apps (browser uploads, mail attachments, Explorer, desktop).
///
/// The data object carries CF_HDROP, plus Shell IDList Array for files on local drives (see
/// [`drag_data_object`]). The drop target picks copy, move or link.
///
/// Call on the UI thread (GPUI has called OleInitialize) while the left button is down.
/// Runs Windows' modal drag loop until drop or cancel; the window keeps repainting.
/// Returns what the target did, or `None` if nothing was dropped. `image` is the
/// precomputed drag image.
pub(crate) fn drag_out(
    paths: &[PathBuf],
    image: Option<&crate::shell::DragImage>,
) -> Result<Option<DragOutcome>, ShellError> {
    use windows::Win32::System::Ole::{DROPEFFECT_COPY, DROPEFFECT_LINK, DROPEFFECT_MOVE};
    use windows::Win32::UI::Shell::SHDoDragDrop;

    if paths.is_empty() {
        return Ok(None);
    }
    // SAFETY: SHDoDragDrop runs on the UI thread, which is OLE-initialized.
    unsafe {
        let data = drag_data_object(paths)?;
        add_hdrop(&data, paths)?;
        if let Some(image) = image {
            crate::win_dragimage::attach(&data, image);
        }
        // Custom drop source: cancel when the cursor returns to the Arke window so Arke's
        // internal drag can take over.
        let home = drag_home();
        let source = drag_source::ReturnAware::new(home);
        let returned = Rc::clone(&source.returned);
        let source: windows::Win32::System::Ole::IDropSource = source.into();
        let effect = SHDoDragDrop(
            None,
            &data,
            &source,
            DROPEFFECT_COPY | DROPEFFECT_MOVE | DROPEFFECT_LINK,
        )?;
        if returned.get() {
            return Ok(Some(DragOutcome::Returned));
        }
        Ok(if effect.0 & DROPEFFECT_MOVE.0 != 0 {
            Some(DragOutcome::Moved)
        } else if effect.0 & (DROPEFFECT_COPY.0 | DROPEFFECT_LINK.0) != 0 {
            Some(DragOutcome::Copied)
        } else {
            None
        })
    }
}

/// The Arke window the drag started in: the one holding the mouse since the press. A press on a
/// window behind another program doesn't activate it (like Explorer, so the window doesn't cover
/// the drop target), so the active window can be none; it is the fallback.
fn drag_home() -> HWND {
    use windows::Win32::UI::Input::KeyboardAndMouse::{GetActiveWindow, GetCapture};
    use windows::Win32::UI::WindowsAndMessaging::{GA_ROOT, GetAncestor};
    // SAFETY: plain queries about this thread's windows.
    unsafe {
        let captured = GetCapture();
        if captured.is_invalid() {
            GetActiveWindow()
        } else {
            GetAncestor(captured, GA_ROOT)
        }
    }
}

/// Puts the paths on `data` as CF_HDROP, the format most drop targets read.
fn add_hdrop(
    data: &windows::Win32::System::Com::IDataObject,
    paths: &[PathBuf],
) -> Result<(), ShellError> {
    use std::mem::ManuallyDrop;
    use windows::Win32::System::Com::{
        DVASPECT_CONTENT, FORMATETC, STGMEDIUM, STGMEDIUM_0, TYMED_HGLOBAL,
    };
    let mut mem = Global::new(&hdrop_bytes(paths))?;
    let format = FORMATETC {
        cfFormat: CF_HDROP.0,
        ptd: std::ptr::null_mut(),
        dwAspect: DVASPECT_CONTENT.0,
        lindex: -1,
        tymed: TYMED_HGLOBAL.0.cast_unsigned(),
    };
    let Some(handle) = mem.handle() else {
        return Err(ShellError::GlobalMemory);
    };
    let medium = STGMEDIUM {
        tymed: TYMED_HGLOBAL.0.cast_unsigned(),
        u: STGMEDIUM_0 {
            hGlobal: HGLOBAL(handle.0),
        },
        pUnkForRelease: ManuallyDrop::new(None),
    };
    // SAFETY: the data object takes ownership of the HGLOBAL once SetData succeeds
    // (fRelease = true); format and medium are valid for the call.
    unsafe {
        data.SetData(
            std::ptr::from_ref(&format),
            std::ptr::from_ref(&medium),
            true,
        )
    }?;
    mem.release();
    Ok(())
}

/// The data object for a drag, before CF_HDROP is added. For files on local drives it also
/// carries Shell IDList Array, as Explorer's drags do: some targets take only that, such as
/// shortcuts on launcher toolbars (#109). `SHCreateDataObject` builds the shell's own object from
/// the PIDLs without binding any handler for the items (Explorer's `GetUIObjectOf` can load a
/// file type's data handler), so no third-party code loads. Network paths keep the plain object:
/// parsing them could wait on the network, and this runs on the UI thread.
///
/// Items of one folder are given as that folder plus one-level child IDs, so the object has the
/// shape of the one Explorer's folder hands out for the same files: a target may expect every ID
/// to be a direct child of the folder in the array, as it always is in Explorer's drags.
/// Items from different folders (search results) use the desktop as the folder and full IDs.
fn drag_data_object(
    paths: &[PathBuf],
) -> windows::core::Result<windows::Win32::System::Com::IDataObject> {
    use windows::Win32::System::Com::{CoTaskMemFree, IDataObject};
    use windows::Win32::UI::Shell::Common::ITEMIDLIST;
    use windows::Win32::UI::Shell::{
        ILFindLastID, IPersistFolder2, SHBindToParent, SHCreateDataObject, SHParseDisplayName,
    };
    struct Pidls(Vec<*mut ITEMIDLIST>);
    impl Drop for Pidls {
        fn drop(&mut self) {
            for pidl in &self.0 {
                // SAFETY: allocated with CoTaskMemAlloc (SHParseDisplayName, GetCurFolder);
                // freed once each.
                unsafe { CoTaskMemFree(Some(pidl.cast_const().cast())) };
            }
        }
    }
    let plain = || {
        // SAFETY: an empty shell data object, no items, nothing loaded.
        unsafe { SHCreateDataObject::<_, IDataObject>(None, None, None::<&IDataObject>) }
    };
    if paths
        .iter()
        .any(|p| crate::global_search::is_network_path(p))
    {
        return plain();
    }
    let parse = |path: &Path| {
        let name = wide(path.as_os_str());
        let mut pidl = std::ptr::null_mut();
        // SAFETY: name is NUL-terminated; pidl is an out variable, owned by the caller on success.
        unsafe { SHParseDisplayName(PCWSTR(name.as_ptr()), None, &raw mut pidl, 0, None) }
            .ok()
            .map(|()| pidl)
    };
    let mut pidls = Pidls(Vec::with_capacity(paths.len() + 1));
    for path in paths {
        let Some(pidl) = parse(path) else {
            return plain();
        };
        pidls.0.push(pidl);
    }
    // The folder's ID as the folder itself gives it (what Explorer's drags carry), which can be
    // shorter than the parsed path's.
    let folder = common_parent(paths).and_then(|_| {
        // SAFETY: the first item's PIDL is valid; the folder's copy of its own ID is
        // CoTaskMemAlloc'ed and freed with the others (Pidls).
        let pidl = unsafe {
            SHBindToParent::<IPersistFolder2>(pidls.0[0].cast_const(), None)
                .and_then(|folder| folder.GetCurFolder())
        }
        .ok()?;
        pidls.0.push(pidl);
        Some(pidl)
    });
    let last_id = |pidl: &*mut ITEMIDLIST| {
        // SAFETY: pidl is a valid, zero-terminated list from SHParseDisplayName; its last ID
        // points into it and stays valid while Pidls is alive.
        unsafe { ILFindLastID(pidl.cast_const()) }.cast_const()
    };
    let (folder, list): (*const ITEMIDLIST, Vec<*const ITEMIDLIST>) = match folder {
        Some(folder) => (
            folder.cast_const(),
            pidls.0[..paths.len()].iter().map(last_id).collect(),
        ),
        // The desktop (an empty PIDL) as the folder, so full PIDLs are its children and items
        // from different folders go in one object.
        None => (
            DESKTOP_PIDL.as_ptr().cast::<ITEMIDLIST>(),
            pidls.0.iter().map(|p| p.cast_const()).collect(),
        ),
    };
    // SAFETY: the folder and item IDs stay alive (Pidls, or the static empty list) for the call,
    // and the data object keeps its own copy.
    unsafe { SHCreateDataObject::<_, IDataObject>(Some(folder), Some(&list), None::<&IDataObject>) }
        .or_else(|_| plain())
}

/// An empty ITEMIDLIST (the desktop): just its zero terminator.
static DESKTOP_PIDL: [u16; 1] = [0];

/// The folder all `paths` are directly in, if there is one (a drive root has none).
fn common_parent(paths: &[PathBuf]) -> Option<&Path> {
    let (first, rest) = paths.split_first()?;
    let parent = first.parent().filter(|p| !p.as_os_str().is_empty())?;
    rest.iter()
        .all(|p| p.parent() == Some(parent))
        .then_some(parent)
}

/// Whether the top-level window under the cursor is another one than `home`: another program's
/// window on top of Arke (a launcher toolbar, an always-on-top window), or outside Arke
/// altogether. Windows that ignore the mouse (the drag image) aren't counted.
pub(crate) fn other_window_at_cursor(home: HWND) -> bool {
    use windows::Win32::UI::WindowsAndMessaging::{
        GA_ROOT, GetAncestor, GetCursorPos, WindowFromPoint,
    };
    if home.is_invalid() {
        return false;
    }
    // SAFETY: plain window queries with valid out pointers.
    unsafe {
        let mut cursor = POINT::default();
        if GetCursorPos(&raw mut cursor).is_err() {
            return false;
        }
        let hit = WindowFromPoint(cursor);
        if hit.is_invalid() {
            return false;
        }
        GetAncestor(hit, GA_ROOT) != home
    }
}

/// The top-level window under the cursor and the cursor in its client area (physical pixels).
pub(crate) fn window_at_cursor() -> Option<(isize, (i32, i32))> {
    use windows::Win32::Graphics::Gdi::ScreenToClient;
    use windows::Win32::UI::WindowsAndMessaging::{
        GA_ROOT, GetAncestor, GetCursorPos, WindowFromPoint,
    };
    // SAFETY: plain window queries with valid out pointers.
    unsafe {
        let mut cursor = POINT::default();
        GetCursorPos(&raw mut cursor).ok()?;
        let hit = WindowFromPoint(cursor);
        if hit.is_invalid() {
            return None;
        }
        let root = GetAncestor(hit, GA_ROOT);
        if root.is_invalid() || !ScreenToClient(root, &raw mut cursor).as_bool() {
            return None;
        }
        Some((root.0 as isize, (cursor.x, cursor.y)))
    }
}

/// What the drop target did with dragged-out files.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum DragOutcome {
    Copied,
    Moved,
    /// Dragged back onto the Arke window; the Windows drag was cancelled.
    Returned,
}

/// Drop source for dragging out. Behaves like the system default (Esc cancels, releasing
/// the button drops, default cursors), but also cancels once the cursor is back inside the
/// Arke client area so Arke's own drag takes over. Otherwise GPUI reports every drop as a
/// copy and drop targets don't highlight. `#[implement]` output trips two pedantic lints,
/// allowed for this module.
#[allow(
    clippy::ref_as_ptr,
    clippy::inline_always,
    reason = "code generated by #[implement]"
)]
mod drag_source {
    use std::cell::Cell;
    use std::rc::Rc;

    use windows::Win32::Foundation::{
        DRAGDROP_S_CANCEL, DRAGDROP_S_DROP, DRAGDROP_S_USEDEFAULTCURSORS, HWND, POINT, RECT,
    };
    use windows::Win32::Graphics::Gdi::ClientToScreen;
    use windows::Win32::System::Ole::{DROPEFFECT, IDropSource, IDropSource_Impl};
    use windows::Win32::System::SystemServices::{MK_LBUTTON, MK_RBUTTON, MODIFIERKEYS_FLAGS};
    use windows::Win32::UI::WindowsAndMessaging::{GetClientRect, GetCursorPos};
    use windows::core::{BOOL, HRESULT};

    /// Distance inside the client edge that counts as "back", so a drag just leaving the
    /// window isn't caught again immediately.
    const INSET: i32 = 8;

    #[windows::core::implement(IDropSource)]
    pub(super) struct ReturnAware {
        home: HWND,
        pub(super) returned: Rc<Cell<bool>>,
    }

    impl ReturnAware {
        pub(super) fn new(home: HWND) -> Self {
            Self {
                home,
                returned: Rc::default(),
            }
        }

        /// Whether the cursor is inside the Arke client area, on Arke itself rather than on
        /// another program's window on top of it (#128).
        fn cursor_home(&self) -> bool {
            if self.home.is_invalid() || super::other_window_at_cursor(self.home) {
                return false;
            }
            // SAFETY: pointers are valid; home is this thread's window and can't close during
            // the drag loop.
            unsafe {
                let mut cursor = POINT::default();
                let mut rect = RECT::default();
                if GetCursorPos(&raw mut cursor).is_err()
                    || GetClientRect(self.home, &raw mut rect).is_err()
                {
                    return false;
                }
                let mut origin = POINT::default();
                if !ClientToScreen(self.home, &raw mut origin).as_bool() {
                    return false;
                }
                let (x, y) = (cursor.x - origin.x, cursor.y - origin.y);
                x >= INSET && y >= INSET && x < rect.right - INSET && y < rect.bottom - INSET
            }
        }
    }

    impl IDropSource_Impl for ReturnAware_Impl {
        fn QueryContinueDrag(&self, escape: BOOL, keys: MODIFIERKEYS_FLAGS) -> HRESULT {
            if escape.as_bool() {
                return DRAGDROP_S_CANCEL;
            }
            if keys.0 & (MK_LBUTTON.0 | MK_RBUTTON.0) == 0 {
                return DRAGDROP_S_DROP;
            }
            if self.cursor_home() {
                self.returned.set(true);
                return DRAGDROP_S_CANCEL;
            }
            HRESULT(0)
        }

        fn GiveFeedback(&self, _effect: DROPEFFECT) -> HRESULT {
            DRAGDROP_S_USEDEFAULTCURSORS
        }
    }
}

/// Owned HGLOBAL. Call `release` once ownership passes to the system; otherwise freed on drop.
struct Global(Option<HGLOBAL>);

impl Global {
    fn new(bytes: &[u8]) -> Result<Self, ShellError> {
        // SAFETY: allocates movable global memory; the locked pointer is valid until unlock and
        // has the same length as bytes.
        unsafe {
            let h = GlobalAlloc(GMEM_MOVEABLE, bytes.len())?;
            let ptr = GlobalLock(h).cast::<u8>();
            if ptr.is_null() {
                let _ = GlobalFree(Some(h));
                return Err(ShellError::ClipboardLock);
            }
            std::ptr::copy_nonoverlapping(bytes.as_ptr(), ptr, bytes.len());
            let _ = GlobalUnlock(h);
            Ok(Self(Some(h)))
        }
    }

    fn handle(&self) -> Option<HANDLE> {
        self.0.map(|h| HANDLE(h.0))
    }

    const fn release(&mut self) {
        self.0 = None;
    }
}

impl Drop for Global {
    fn drop(&mut self) {
        if let Some(h) = self.0.take() {
            // SAFETY: h was allocated here and not handed to the system.
            let _ = unsafe { GlobalFree(Some(h)) };
        }
    }
}

/// Paths in an HDROP.
pub(crate) fn parse_hdrop(hdrop: HDROP) -> Vec<PathBuf> {
    // SAFETY: hdrop is valid CF_HDROP memory; u32::MAX queries the count, then each buffer is
    // sized from the reported length.
    unsafe {
        let count = DragQueryFileW(hdrop, u32::MAX, None);
        (0..count)
            .map(|i| {
                let len = DragQueryFileW(hdrop, i, None) as usize;
                let mut buf = vec![0u16; len + 1];
                let n = DragQueryFileW(hdrop, i, Some(&mut buf)) as usize;
                PathBuf::from(OsString::from_wide(&buf[..n.min(len)]))
            })
            .collect()
    }
}

/// Open clipboard, closed on drop.
struct OpenedClipboard;

impl OpenedClipboard {
    /// Retries for about 0.5 s while another app holds the clipboard.
    fn open(owner: Option<HWND>) -> Result<Self, ShellError> {
        for _ in 0..25 {
            // SAFETY: owner is None or a window created on this thread.
            if unsafe { OpenClipboard(owner) }.is_ok() {
                return Ok(Self);
            }
            std::thread::sleep(Duration::from_millis(20));
        }
        Err(ShellError::ClipboardBusy)
    }
}

impl Drop for OpenedClipboard {
    fn drop(&mut self) {
        // SAFETY: pairs with a successful OpenClipboard.
        let _ = unsafe { CloseClipboard() };
    }
}

/// Hidden window used only as clipboard owner; SetClipboardData fails after OpenClipboard(NULL).
struct MessageWindow(HWND);

impl MessageWindow {
    fn new() -> Result<Self, ShellError> {
        // SAFETY: creates a message-only window (parent HWND_MESSAGE) with the built-in STATIC class.
        let hwnd = unsafe {
            CreateWindowExW(
                WINDOW_EX_STYLE(0),
                w!("STATIC"),
                w!("arke-clipboard"),
                WINDOW_STYLE(0),
                0,
                0,
                0,
                0,
                Some(HWND_MESSAGE),
                None,
                None,
                None,
            )
        }?;
        Ok(Self(hwnd))
    }
}

impl Drop for MessageWindow {
    fn drop(&mut self) {
        // SAFETY: self.0 was created by this struct on the same thread.
        let _ = unsafe { DestroyWindow(self.0) };
    }
}

fn drop_effect_format() -> u32 {
    // SAFETY: the argument is a static wide string.
    unsafe { RegisterClipboardFormatW(w!("Preferred DropEffect")) }
}

/// Shell data object, the same kind Explorer puts on the clipboard (CF_HDROP, Shell IDList
/// Array, file names, ...) plus Preferred DropEffect. Needed for Explorer's "Paste shortcut"
/// and apps like Outlook that only accept shell formats. Parsing network paths can block, so
/// call from a background thread with COM initialized.
pub(crate) fn shell_data_object(
    paths: &[PathBuf],
    cut: bool,
) -> Result<windows::Win32::System::Com::IDataObject, ShellError> {
    use std::mem::ManuallyDrop;
    use windows::Win32::System::Com::{
        CoTaskMemFree, DVASPECT_CONTENT, FORMATETC, IDataObject, STGMEDIUM, STGMEDIUM_0,
        TYMED_HGLOBAL,
    };
    use windows::Win32::UI::Shell::Common::ITEMIDLIST;
    use windows::Win32::UI::Shell::{
        BHID_DataObject, IShellItemArray, SHCreateShellItemArrayFromIDLists, SHParseDisplayName,
    };
    /// Parsed PIDLs, freed together.
    struct Pidls(Vec<*mut ITEMIDLIST>);
    impl Drop for Pidls {
        fn drop(&mut self) {
            for pidl in &self.0 {
                // SAFETY: allocated by SHParseDisplayName with CoTaskMemAlloc; freed once each.
                unsafe { CoTaskMemFree(Some(pidl.cast_const().cast())) };
            }
        }
    }
    if paths.is_empty() {
        return Err(ShellError::ClipboardEmpty);
    }
    let mut pidls = Pidls(Vec::with_capacity(paths.len()));
    for path in paths {
        let name = wide(path.as_os_str());
        let mut pidl = std::ptr::null_mut();
        // SAFETY: name is NUL-terminated; pidl is an out variable owned by Pidls on success.
        unsafe { SHParseDisplayName(PCWSTR(name.as_ptr()), None, &raw mut pidl, 0, None) }?;
        pidls.0.push(pidl);
    }
    let list: Vec<*const ITEMIDLIST> = pidls.0.iter().map(|p| p.cast_const()).collect();
    // SAFETY: the PIDLs in list stay alive (Pidls) for the call; the array and data object
    // keep their own copies.
    let object: IDataObject = unsafe {
        let array: IShellItemArray = SHCreateShellItemArrayFromIDLists(&list)?;
        array.BindToHandler(None, &BHID_DataObject)?
    };
    // Explorer uses COPY|LINK for copy and MOVE for cut.
    let effect = if cut {
        DROPEFFECT_MOVE
    } else {
        DROPEFFECT_COPY | DROPEFFECT_LINK
    };
    let mut mem = Global::new(&effect.to_le_bytes())?;
    let Some(handle) = mem.handle() else {
        return Err(ShellError::GlobalMemory);
    };
    let format = FORMATETC {
        cfFormat: u16::try_from(drop_effect_format()).unwrap_or_default(),
        ptd: std::ptr::null_mut(),
        dwAspect: DVASPECT_CONTENT.0,
        lindex: -1,
        tymed: TYMED_HGLOBAL.0.cast_unsigned(),
    };
    let medium = STGMEDIUM {
        tymed: TYMED_HGLOBAL.0.cast_unsigned(),
        u: STGMEDIUM_0 {
            hGlobal: HGLOBAL(handle.0),
        },
        pUnkForRelease: ManuallyDrop::new(None),
    };
    // SAFETY: format and medium are valid for the call; with fRelease = true the data object
    // owns the memory on success.
    unsafe {
        object.SetData(
            std::ptr::from_ref(&format),
            std::ptr::from_ref(&medium),
            true,
        )
    }?;
    mem.release();
    Ok(object)
}

/// Puts a shell data object on the clipboard and flushes it (`OleFlushClipboard`) so the
/// data no longer depends on this thread or object staying alive.
fn set_clipboard_shell(files: &ClipboardFiles) -> Result<(), ShellError> {
    use windows::Win32::System::Ole::{
        OleFlushClipboard, OleInitialize, OleSetClipboard, OleUninitialize,
    };
    // SAFETY: OLE init on this background thread, paired with OleUninitialize only on success.
    unsafe { OleInitialize(None) }?;
    let result = (|| {
        let object = shell_data_object(&files.paths, files.cut)?;
        // SAFETY: object is a valid data object; OLE is initialized on this thread.
        unsafe {
            OleSetClipboard(&object)?;
            OleFlushClipboard().map_err(ShellError::from)
        }
    })();
    // SAFETY: pairs with the successful OleInitialize above.
    unsafe { OleUninitialize() };
    result
}

pub(crate) fn set_clipboard_files(files: &ClipboardFiles) -> Result<u32, ShellError> {
    // Prefer the shell data object (most formats); if e.g. a path can't be parsed, fall back
    // to a hand-built CF_HDROP.
    match set_clipboard_shell(files) {
        // SAFETY: only reads the sequence number.
        Ok(()) => return Ok(unsafe { GetClipboardSequenceNumber() }),
        Err(err) => log::info!("clipboard falling back to CF_HDROP: {err}"),
    }
    let mut hdrop = Global::new(&hdrop_bytes(&files.paths))?;
    // Explorer uses COPY|LINK for copy and MOVE for cut.
    let effect = if files.cut {
        DROPEFFECT_MOVE
    } else {
        DROPEFFECT_COPY | DROPEFFECT_LINK
    };
    let mut effect_mem = Global::new(&effect.to_le_bytes())?;
    let window = MessageWindow::new()?;
    {
        let _clipboard = OpenedClipboard::open(Some(window.0))?;
        // SAFETY: the clipboard is open on this thread; after SetClipboardData succeeds the
        // system owns the memory, hence release.
        unsafe {
            EmptyClipboard()?;
            SetClipboardData(u32::from(CF_HDROP.0), hdrop.handle())?;
            hdrop.release();
            if SetClipboardData(drop_effect_format(), effect_mem.handle()).is_ok() {
                effect_mem.release();
            }
        }
    }
    // SAFETY: only reads the sequence number.
    Ok(unsafe { GetClipboardSequenceNumber() })
}

pub(crate) fn set_clipboard_text(text: &str) -> Result<(), ShellError> {
    let units: Vec<u16> = text.encode_utf16().chain(std::iter::once(0)).collect();
    let bytes: Vec<u8> = units.iter().flat_map(|u| u.to_le_bytes()).collect();
    let mut mem = Global::new(&bytes)?;
    let window = MessageWindow::new()?;
    let _clipboard = OpenedClipboard::open(Some(window.0))?;
    // SAFETY: the clipboard is open on this thread; the system owns the memory on success.
    unsafe {
        EmptyClipboard()?;
        SetClipboardData(u32::from(CF_UNICODETEXT.0), mem.handle())?;
    }
    mem.release();
    Ok(())
}

pub(crate) fn clipboard_files() -> Result<Option<(ClipboardFiles, u32)>, ShellError> {
    // SAFETY: only queries the sequence number and format; the clipboard isn't opened.
    let (seq, available) = unsafe {
        (
            GetClipboardSequenceNumber(),
            IsClipboardFormatAvailable(u32::from(CF_HDROP.0)).is_ok(),
        )
    };
    if !available {
        return Ok(None);
    }
    let _clipboard = OpenedClipboard::open(None)?;
    // SAFETY: the clipboard is open; the handles belong to the clipboard and are only read
    // before it closes, never freed.
    unsafe {
        let Ok(handle) = GetClipboardData(u32::from(CF_HDROP.0)) else {
            return Ok(None);
        };
        let paths = parse_hdrop(HDROP(handle.0));
        let cut = GetClipboardData(drop_effect_format())
            .ok()
            .and_then(|h| {
                let mem = HGLOBAL(h.0);
                let ptr = GlobalLock(mem).cast::<u32>();
                if ptr.is_null() {
                    return None;
                }
                let value = ptr.read_unaligned();
                let _ = GlobalUnlock(mem);
                Some(value)
            })
            .is_some_and(|effect| effect & DROPEFFECT_MOVE != 0);
        Ok((!paths.is_empty()).then_some((ClipboardFiles { paths, cut }, seq)))
    }
}

pub(crate) fn clear_clipboard_if(seq: u32) {
    // SAFETY: only reads the sequence number. Clear only if unchanged, so content copied
    // later is kept.
    if unsafe { GetClipboardSequenceNumber() } != seq {
        return;
    }
    if let Ok(_clipboard) = OpenedClipboard::open(None) {
        // SAFETY: the clipboard is open.
        let _ = unsafe { EmptyClipboard() };
    }
}

pub(crate) fn clipboard_seq() -> u32 {
    // SAFETY: only reads the sequence number; non-blocking.
    unsafe { GetClipboardSequenceNumber() }
}

pub(crate) fn clipboard_has_files() -> bool {
    // SAFETY: only checks format availability; non-blocking.
    unsafe { IsClipboardFormatAvailable(u32::from(CF_HDROP.0)) }.is_ok()
        || crate::win_virtual_drop::clipboard_has_virtual_files()
}

