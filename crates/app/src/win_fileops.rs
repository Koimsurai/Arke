/// Drags files out to other apps (browser uploads, mail attachments, Explorer, desktop).
///
/// The data object carries only CF_HDROP, the same format Explorer drags, so this never
/// touches the file system or network. The drop target picks copy, move or link.
///
/// Call on the UI thread (GPUI has called OleInitialize) while the left button is down.
/// Runs Windows' modal drag loop until drop or cancel; the window keeps repainting.
/// Returns what the target did, or `None` if nothing was dropped. `image` is the
/// precomputed drag image.
pub(crate) fn drag_out(
    paths: &[PathBuf],
    image: Option<&crate::shell::DragImage>,
) -> Result<Option<DragOutcome>, ShellError> {
    use std::mem::ManuallyDrop;
    use windows::Win32::System::Com::{
        DVASPECT_CONTENT, FORMATETC, IDataObject, STGMEDIUM, STGMEDIUM_0, TYMED_HGLOBAL,
    };
    use windows::Win32::System::Ole::{DROPEFFECT_COPY, DROPEFFECT_LINK, DROPEFFECT_MOVE};
    use windows::Win32::UI::Shell::{SHCreateDataObject, SHDoDragDrop};

    if paths.is_empty() {
        return Ok(None);
    }
    let mut mem = Global::new(&hdrop_bytes(paths))?;
    // SAFETY: an empty shell data object (no items, no extensions loaded) takes ownership of
    // the HGLOBAL once SetData succeeds (fRelease = true). SHDoDragDrop runs on the UI thread,
    // which is OLE-initialized.
    unsafe {
        let data: IDataObject = SHCreateDataObject(None, None, None::<&IDataObject>)?;
        let format = FORMATETC {
            cfFormat: CF_HDROP.0,
            ptd: std::ptr::null_mut(),
            dwAspect: DVASPECT_CONTENT.0,
            lindex: -1,
            tymed: TYMED_HGLOBAL.0.cast_unsigned(),
        };
        let Some(handle) = mem.handle() else {
            return Err(ShellError::GlobalMemory);
        };
        let medium = STGMEDIUM {
            tymed: TYMED_HGLOBAL.0.cast_unsigned(),
            u: STGMEDIUM_0 {
                hGlobal: HGLOBAL(handle.0),
            },
            pUnkForRelease: ManuallyDrop::new(None),
        };
        data.SetData(
            std::ptr::from_ref(&format),
            std::ptr::from_ref(&medium),
            true,
        )?;
        mem.release();
        if let Some(image) = image {
            crate::win_dragimage::attach(&data, image);
        }
        // Custom drop source: cancel when the cursor returns to the Arke window so Arke's
        // internal drag can take over.
        let home = windows::Win32::UI::Input::KeyboardAndMouse::GetActiveWindow();
        let source = drag_source::ReturnAware::new(home);
        let returned = source.returned.clone();
        let source: windows::Win32::System::Ole::IDropSource = source.into();
        let effect = SHDoDragDrop(
            None,
            &data,
            &source,
            DROPEFFECT_COPY | DROPEFFECT_MOVE | DROPEFFECT_LINK,
        )?;
        if returned.get() {
            return Ok(Some(DragOutcome::Returned));
        }
        Ok(if effect.0 & DROPEFFECT_MOVE.0 != 0 {
            Some(DragOutcome::Moved)
        } else if effect.0 & (DROPEFFECT_COPY.0 | DROPEFFECT_LINK.0) != 0 {
            Some(DragOutcome::Copied)
        } else {
            None
        })
    }
}

/// What the drop target did with dragged-out files.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum DragOutcome {
    Copied,
    Moved,
    /// Dragged back onto the Arke window; the Windows drag was cancelled.
    Returned,
}

/// Drop source for dragging out. Behaves like the system default (Esc cancels, releasing
/// the button drops, default cursors), but also cancels once the cursor is back inside the
/// Arke client area so Arke's own drag takes over. Otherwise GPUI reports every drop as a
/// copy and drop targets don't highlight. `#[implement]` output trips two pedantic lints,
/// allowed for this module.
#[allow(clippy::ref_as_ptr, clippy::inline_always)]
mod drag_source {
    use std::cell::Cell;
    use std::rc::Rc;

    use windows::Win32::Foundation::{
        DRAGDROP_S_CANCEL, DRAGDROP_S_DROP, DRAGDROP_S_USEDEFAULTCURSORS, HWND, POINT, RECT,
    };
    use windows::Win32::Graphics::Gdi::ClientToScreen;
    use windows::Win32::System::Ole::{DROPEFFECT, IDropSource, IDropSource_Impl};
    use windows::Win32::System::SystemServices::{MK_LBUTTON, MK_RBUTTON, MODIFIERKEYS_FLAGS};
    use windows::Win32::UI::WindowsAndMessaging::{GetClientRect, GetCursorPos};
    use windows::core::{BOOL, HRESULT};

    /// Distance inside the client edge that counts as "back", so a drag just leaving the
    /// window isn't caught again immediately.
    const INSET: i32 = 8;

    #[windows::core::implement(IDropSource)]
    pub(super) struct ReturnAware {
        home: HWND,
        pub(super) returned: Rc<Cell<bool>>,
    }

    impl ReturnAware {
        pub(super) fn new(home: HWND) -> Self {
            Self {
                home,
                returned: Rc::default(),
            }
        }

        /// Whether the cursor is inside the Arke client area.
        fn cursor_home(&self) -> bool {
            if self.home.is_invalid() {
                return false;
            }
            // SAFETY: pointers are valid; home is this thread's window and can't close during
            // the drag loop.
            unsafe {
                let mut cursor = POINT::default();
                let mut rect = RECT::default();
                if GetCursorPos(&raw mut cursor).is_err()
                    || GetClientRect(self.home, &raw mut rect).is_err()
                {
                    return false;
                }
                let mut origin = POINT::default();
                if !ClientToScreen(self.home, &raw mut origin).as_bool() {
                    return false;
                }
                let (x, y) = (cursor.x - origin.x, cursor.y - origin.y);
                x >= INSET && y >= INSET && x < rect.right - INSET && y < rect.bottom - INSET
            }
        }
    }

    impl IDropSource_Impl for ReturnAware_Impl {
        fn QueryContinueDrag(&self, escape: BOOL, keys: MODIFIERKEYS_FLAGS) -> HRESULT {
            if escape.as_bool() {
                return DRAGDROP_S_CANCEL;
            }
            if keys.0 & (MK_LBUTTON.0 | MK_RBUTTON.0) == 0 {
                return DRAGDROP_S_DROP;
            }
            if self.cursor_home() {
                self.returned.set(true);
                return DRAGDROP_S_CANCEL;
            }
            HRESULT(0)
        }

        fn GiveFeedback(&self, _effect: DROPEFFECT) -> HRESULT {
            DRAGDROP_S_USEDEFAULTCURSORS
        }
    }
}

/// Owned HGLOBAL. Call `release` once ownership passes to the system; otherwise freed on drop.
struct Global(Option<HGLOBAL>);

impl Global {
    fn new(bytes: &[u8]) -> Result<Self, ShellError> {
        // SAFETY: allocates movable global memory; the locked pointer is valid until unlock and
        // has the same length as bytes.
        unsafe {
            let h = GlobalAlloc(GMEM_MOVEABLE, bytes.len())?;
            let ptr = GlobalLock(h).cast::<u8>();
            if ptr.is_null() {
                let _ = GlobalFree(Some(h));
                return Err(ShellError::ClipboardLock);
            }
            std::ptr::copy_nonoverlapping(bytes.as_ptr(), ptr, bytes.len());
            let _ = GlobalUnlock(h);
            Ok(Self(Some(h)))
        }
    }

    fn handle(&self) -> Option<HANDLE> {
        self.0.map(|h| HANDLE(h.0))
    }

    const fn release(&mut self) {
        self.0 = None;
    }
}

impl Drop for Global {
    fn drop(&mut self) {
        if let Some(h) = self.0.take() {
            // SAFETY: h was allocated here and not handed to the system.
            let _ = unsafe { GlobalFree(Some(h)) };
        }
    }
}

/// Paths in an HDROP.
pub(crate) fn parse_hdrop(hdrop: HDROP) -> Vec<PathBuf> {
    // SAFETY: hdrop is valid CF_HDROP memory; u32::MAX queries the count, then each buffer is
    // sized from the reported length.
    unsafe {
        let count = DragQueryFileW(hdrop, u32::MAX, None);
        (0..count)
            .map(|i| {
                let len = DragQueryFileW(hdrop, i, None) as usize;
                let mut buf = vec![0u16; len + 1];
                let n = DragQueryFileW(hdrop, i, Some(&mut buf)) as usize;
                PathBuf::from(OsString::from_wide(&buf[..n.min(len)]))
            })
            .collect()
    }
}

/// Open clipboard, closed on drop.
struct OpenedClipboard;

impl OpenedClipboard {
    /// Retries for about 0.5 s while another app holds the clipboard.
    fn open(owner: Option<HWND>) -> Result<Self, ShellError> {
        for _ in 0..25 {
            // SAFETY: owner is None or a window created on this thread.
            if unsafe { OpenClipboard(owner) }.is_ok() {
                return Ok(Self);
            }
            std::thread::sleep(Duration::from_millis(20));
        }
        Err(ShellError::ClipboardBusy)
    }
}

impl Drop for OpenedClipboard {
    fn drop(&mut self) {
        // SAFETY: pairs with a successful OpenClipboard.
        let _ = unsafe { CloseClipboard() };
    }
}

/// Hidden window used only as clipboard owner; SetClipboardData fails after OpenClipboard(NULL).
struct MessageWindow(HWND);

impl MessageWindow {
    fn new() -> Result<Self, ShellError> {
        // SAFETY: creates a message-only window (parent HWND_MESSAGE) with the built-in STATIC class.
        let hwnd = unsafe {
            CreateWindowExW(
                WINDOW_EX_STYLE(0),
                w!("STATIC"),
                w!("arke-clipboard"),
                WINDOW_STYLE(0),
                0,
                0,
                0,
                0,
                Some(HWND_MESSAGE),
                None,
                None,
                None,
            )
        }?;
        Ok(Self(hwnd))
    }
}

impl Drop for MessageWindow {
    fn drop(&mut self) {
        // SAFETY: self.0 was created by this struct on the same thread.
        let _ = unsafe { DestroyWindow(self.0) };
    }
}

