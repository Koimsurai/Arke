pub(crate) fn wide(s: &std::ffi::OsStr) -> Vec<u16> {
    s.encode_wide().chain(std::iter::once(0)).collect()
}

pub(crate) fn message(err: &windows::core::Error) -> String {
    let msg = err.message();
    let msg = msg.trim();
    if msg.is_empty() {
        format!("{:#010x}", err.code().0)
    } else {
        msg.to_owned()
    }
}

/// COM (STA) on the current thread, uninitialized on drop.
pub(crate) struct Com;

impl Com {
    pub(crate) fn init() -> Result<Self, ShellError> {
        // SAFETY: initializes an STA on the caller's thread; on success (including S_FALSE)
        // Drop pairs it with CoUninitialize.
        unsafe { CoInitializeEx(None, COINIT_APARTMENTTHREADED | COINIT_DISABLE_OLE1DDE) }.ok()?;
        Ok(Self)
    }
}

impl Drop for Com {
    fn drop(&mut self) {
        // SAFETY: pairs with the successful CoInitializeEx in init.
        unsafe { CoUninitialize() };
    }
}

fn shell_item(path: &Path) -> Result<IShellItem, ShellError> {
    let w = wide(path.as_os_str());
    // SAFETY: w is a NUL-terminated wide string that outlives the call.
    unsafe { SHCreateItemFromParsingName(PCWSTR(w.as_ptr()), None) }.map_err(|source| {
        ShellError::Path {
            path: path.to_path_buf(),
            source,
        }
    })
}

