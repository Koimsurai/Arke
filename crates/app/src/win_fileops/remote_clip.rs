    /// Each descriptor has the item's relative name, a folder's attribute or a file's size, and
    /// the time when it is known.
    #[test]
    fn descriptors_hold_relative_names_folders_sizes_and_times() {
        let time = SystemTime::UNIX_EPOCH + Duration::from_secs(1_767_323_045);
        let file = RemoteUrl::from_path(std::path::Path::new("mtp://phone/DCIM/a.jpg")).unwrap();
        let items = [
            VirtualItem {
                rel: "DCIM".into(),
                url: None,
                size: None,
                modified: Some(time),
            },
            VirtualItem {
                rel: r"DCIM\a.jpg".into(),
                url: Some(file),
                size: Some(5_000_000_000),
                modified: None,
            },
        ];
        let bytes = descriptor_bytes(&items);
        let size = size_of::<FILEDESCRIPTORW>();
        assert_eq!(bytes.len(), 4 + 2 * size);
        assert_eq!(u32::from_le_bytes(bytes[..4].try_into().unwrap()), 2);
        // SAFETY: each slice holds one (unaligned) FILEDESCRIPTORW.
        let read = |i: usize| unsafe {
            bytes[4 + i * size..]
                .as_ptr()
                .cast::<FILEDESCRIPTORW>()
                .read_unaligned()
        };
        let (folder, photo) = (read(0), read(1));
        let flag = |f: windows::Win32::UI::Shell::FD_FLAGS| f.0.cast_unsigned();

        assert_eq!(name_of(&folder), "DCIM");
        let (attributes, flags, written) = (
            folder.dwFileAttributes,
            folder.dwFlags,
            folder.ftLastWriteTime,
        );
        assert_ne!(attributes & FILE_ATTRIBUTE_DIRECTORY.0, 0);
        assert_ne!(flags & flag(FD_ATTRIBUTES), 0);
        assert_eq!(flags & flag(FD_FILESIZE), 0, "a folder has no size");
        assert_ne!(flags & flag(FD_WRITESTIME), 0);
        assert_eq!(Some(written), filetime(time));

        assert_eq!(name_of(&photo), r"DCIM\a.jpg");
        let (attributes, flags, high, low) = (
            photo.dwFileAttributes,
            photo.dwFlags,
            photo.nFileSizeHigh,
            photo.nFileSizeLow,
        );
        assert_eq!(attributes & FILE_ATTRIBUTE_DIRECTORY.0, 0);
        assert_ne!(flags & flag(FD_FILESIZE), 0);
        assert_eq!(flags & flag(FD_WRITESTIME), 0, "no time was listed");
        assert_eq!((u64::from(high) << 32) | u64::from(low), 5_000_000_000);
    }

