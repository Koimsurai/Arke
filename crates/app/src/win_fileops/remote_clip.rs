/// Remote items as virtual files (see the module docs).
#[implement(IDataObject, Agile = false)]
struct RemoteData {
    items: Arc<RemoteItems>,
    /// `Preferred DropEffect`: move for a cut, else copy.
    effect: u32,
    /// What other code sets on it (a drag image, a drop description, how a paste went), kept in
    /// a shell data object of its own.
    store: IDataObject,
    /// Lists the items when first asked. A drag's are listed before (its object lives on the UI
    /// thread, which must never wait on the server).
    may_list: bool,
}

impl RemoteData {
    fn create(
        items: Arc<RemoteItems>,
        effect: u32,
        may_list: bool,
    ) -> windows::core::Result<IDataObject> {
        // SAFETY: an empty shell data object, no items, nothing loaded.
        let store =
            unsafe { SHCreateDataObject::<_, IDataObject>(None, None, None::<&IDataObject>) }?;
        Ok(Self {
            items,
            effect,
            store,
            may_list,
        }
        .into())
    }
}

impl RemoteData {
    fn listing(&self) -> windows::core::Result<Arc<Listing>> {
        if !self.may_list {
            return self.items.listed().ok_or_else(|| DV_E_FORMATETC.into());
        }
        self.items.listing().map_err(|err| {
            log::info!("remote items not listed for another program: {err}");
            hresult_of(&err).into()
        })
    }

    /// Item `index`'s bytes as a stream.
    fn contents(&self, index: i32) -> windows::core::Result<STGMEDIUM> {
        let listing = self.listing()?;
        let at = usize::try_from(index)
            .ok()
            .filter(|at| *at < listing.items.len())
            .ok_or(DV_E_LINDEX)?;
        let item = &listing.items[at];
        // A folder has no contents.
        let url = item.url.clone().ok_or(DV_E_LINDEX)?;
        let name = item.rel.rsplit('\\').next().unwrap_or(&item.rel).to_owned();
        let stream = make_stream(Source {
            remotes: Arc::clone(&self.items.remotes),
            url,
            name,
            size: item.size,
            modified: item.modified.and_then(filetime),
            listing: Arc::clone(&listing),
            index: at,
        })?;
        Ok(STGMEDIUM {
            tymed: TYMED_ISTREAM.0.cast_unsigned(),
            u: STGMEDIUM_0 {
                pstm: ManuallyDrop::new(Some(stream)),
            },
            pUnkForRelease: ManuallyDrop::new(None),
        })
    }

    /// Another program says what its paste or drop did (`format`, see [`Formats::reported`]).
    /// It can't move virtual files itself, so a move of a cut is finished here: the originals it
    /// read in full are deleted now, the others once their reads complete. Each goes once.
    fn reported(&self, format: &str, effect: u32) {
        let listing = self.items.listed();
        log::debug!(
            target: LOG,
            "{format} = {effect:#x}: cut {}, listed {}, read in full {:?}",
            self.items.cut,
            listing.is_some(),
            listing.as_ref().map(|l| l.fully_read()),
        );
        if !self.items.cut || effect & DROPEFFECT_MOVE == 0 {
            return;
        }
        let Some(listing) = listing else {
            return;
        };
        listing.set_moved_out();
        delete_moved(&self.items.remotes, listing.take_fully_read());
    }
}

impl IDataObject_Impl for RemoteData_Impl {
    fn GetData(&self, format: *const FORMATETC) -> windows::core::Result<STGMEDIUM> {
        // SAFETY: the caller passes a valid FORMATETC (or null, refused).
        let Some(asked) = (unsafe { format.as_ref() }) else {
            return Err(E_INVALIDARG.into());
        };
        let formats = Formats::get();
        if log::log_enabled!(target: LOG, log::Level::Debug) {
            log::debug!(
                target: LOG,
                "another program asks for {} (index {}, tymed {})",
                format_name(asked.cfFormat),
                asked.lindex,
                asked.tymed,
            );
        }
        if asked.cfFormat == formats.contents {
            if asked.tymed & TYMED_ISTREAM.0.cast_unsigned() == 0 {
                return Err(DV_E_TYMED.into());
            }
            return self.contents(asked.lindex);
        }
        if formats.in_memory(asked.cfFormat) {
            if asked.tymed & TYMED_HGLOBAL.0.cast_unsigned() == 0 {
                return Err(DV_E_TYMED.into());
            }
            if asked.cfFormat == formats.descriptor {
                return global_medium(&descriptor_bytes(&self.listing()?.items));
            }
            return global_medium(&self.effect.to_le_bytes());
        }
        // SAFETY: the caller's request, passed on as it came.
        unsafe { self.store.GetData(format) }
    }

    fn GetDataHere(
        &self,
        format: *const FORMATETC,
        medium: *mut STGMEDIUM,
    ) -> windows::core::Result<()> {
        // SAFETY: the caller's request, passed on as it came.
        unsafe { self.store.GetDataHere(format, medium) }
    }

    fn QueryGetData(&self, format: *const FORMATETC) -> HRESULT {
        // SAFETY: the caller passes a valid FORMATETC (or null, refused).
        let Some(asked) = (unsafe { format.as_ref() }) else {
            return E_INVALIDARG;
        };
        let formats = Formats::get();
        let tymed = if asked.cfFormat == formats.contents {
            TYMED_ISTREAM
        } else if formats.in_memory(asked.cfFormat) {
            TYMED_HGLOBAL
        } else {
            // SAFETY: the caller's request, passed on as it came.
            return unsafe { self.store.QueryGetData(format) };
        };
        if asked.tymed & tymed.0.cast_unsigned() == 0 {
            DV_E_TYMED
        } else {
            S_OK
        }
    }

    fn GetCanonicalFormatEtc(&self, format: *const FORMATETC, out: *mut FORMATETC) -> HRESULT {
        // SAFETY: the caller's request, passed on as it came.
        unsafe { self.store.GetCanonicalFormatEtc(format, out) }
    }

    fn SetData(
        &self,
        format: *const FORMATETC,
        medium: *const STGMEDIUM,
        release: BOOL,
    ) -> windows::core::Result<()> {
        // SAFETY: the caller's FORMATETC and medium, valid for the call (or null).
        let (asked, given) = unsafe { (format.as_ref(), medium.as_ref()) };
        if let (Some(asked), Some(given)) = (asked, given) {
            if log::log_enabled!(target: LOG, log::Level::Debug) {
                // SAFETY: the caller's valid medium.
                let value = unsafe { describe_medium(given) };
                let name = format_name(asked.cfFormat);
                log::debug!(target: LOG, "another program sets {name}: {value}");
            }
            if let Some(name) = Formats::get().reported(asked.cfFormat)
                // SAFETY: the caller's valid medium.
                && let Some(effect) = unsafe { medium_number(given) }
            {
                self.reported(name, effect);
            }
        }
        // SAFETY: the caller's data, passed on with its ownership.
        unsafe { self.store.SetData(format, medium, release.as_bool()) }
    }

    fn EnumFormatEtc(&self, direction: u32) -> windows::core::Result<IEnumFORMATETC> {
        if direction != DATADIR_GET.0.cast_unsigned() {
            return Err(E_NOTIMPL.into());
        }
        let formats = Formats::get();
        let mut list = vec![
            format_of(formats.descriptor, TYMED_HGLOBAL),
            format_of(formats.contents, TYMED_ISTREAM),
            format_of(formats.effect, TYMED_HGLOBAL),
        ];
        // And what was set on it (a drag image), which drop targets look for.
        // SAFETY: asks the store for its formats.
        if let Ok(set) = unsafe { self.store.EnumFormatEtc(direction) } {
            let mut one = [FORMATETC::default()];
            let mut got = 0u32;
            // SAFETY: room for one format and its count.
            while unsafe { set.Next(&mut one, Some(&raw mut got)) } == S_OK && got == 1 {
                if !one[0].ptd.is_null() {
                    // SAFETY: the enumerator's copy of a target device is the caller's to free.
                    unsafe { CoTaskMemFree(Some(one[0].ptd.cast_const().cast())) };
                    one[0].ptd = std::ptr::null_mut();
                }
                let cf = one[0].cfFormat;
                if cf != formats.contents && !formats.in_memory(cf) {
                    list.push(one[0]);
                }
            }
        }
        // SAFETY: the formats are valid for the call; the enumerator keeps a copy.
        unsafe { SHCreateStdEnumFmtEtc(&list) }
    }

    fn DAdvise(
        &self,
        _: *const FORMATETC,
        _: u32,
        _: Ref<IAdviseSink>,
    ) -> windows::core::Result<u32> {
        Err(OLE_E_ADVISENOTSUPPORTED.into())
    }

    fn DUnadvise(&self, _: u32) -> windows::core::Result<()> {
        Err(OLE_E_ADVISENOTSUPPORTED.into())
    }

    fn EnumDAdvise(&self) -> windows::core::Result<IEnumSTATDATA> {
        Err(OLE_E_ADVISENOTSUPPORTED.into())
    }
}

// ───────────────────────── Clipboard and drags ─────────────────────────

/// The clipboard sequence number, and the window that owned the clipboard, right after Arke put
/// remote items there.
static PLACED: Mutex<Option<(u32, usize)>> = Mutex::new(None);

thread_local! {
    /// On the owner thread: whether it has OLE yet.
    static OLE: Cell<bool> = const { Cell::new(false) };
    /// On the owner thread: the data object Arke last put on the clipboard.
    static ON_CLIPBOARD: RefCell<Option<IDataObject>> = const { RefCell::new(None) };
}

/// Puts remote items on the clipboard as virtual files and returns the clipboard sequence
/// number. Nothing is listed or downloaded here. Background thread.
pub(crate) fn set_clipboard(items: &Arc<RemoteItems>) -> Result<u32, ShellError> {
    let items = Arc::clone(items);
    super::lazy_clipboard::on_owner(true, Duration::from_secs(30), move || place(items))?
}

/// On the clipboard owner thread, which keeps pumping messages for the programs that read the
/// object.
fn place(items: Arc<RemoteItems>) -> Result<u32, ShellError> {
    if !OLE.get() {
        // SAFETY: OLE for the owner thread for the rest of the process (never undone).
        unsafe { OleInitialize(None) }?;
        OLE.set(true);
    }
    let effect = if items.cut {
        DROPEFFECT_MOVE
    } else {
        DROPEFFECT_COPY
    };
    let count = items.sources.len();
    let data = RemoteData::create(items, effect, true)?;
    let mut tries = 0;
    loop {
        // SAFETY: OLE is initialized on this thread, which pumps messages.
        match unsafe { OleSetClipboard(&data) } {
            Ok(()) => break,
            // Another program holds the clipboard: wait a little, as for files.
            Err(err) if err.code() == CLIPBRD_E_CANT_OPEN && tries < 25 => {
                tries += 1;
                std::thread::sleep(Duration::from_millis(20));
            }
            Err(err) if err.code() == CLIPBRD_E_CANT_OPEN => return Err(ShellError::ClipboardBusy),
            Err(err) => return Err(err.into()),
        }
    }
    // SAFETY: plain queries.
    let (seq, owner) = unsafe {
        (
            GetClipboardSequenceNumber(),
            GetClipboardOwner().map_or(0, |h| h.0.expose_provenance()),
        )
    };
    log::debug!(
        target: LOG,
        "on the clipboard: {count} items, effect {effect:#x}, sequence {seq}"
    );
    *PLACED.lock() = Some((seq, owner));
    ON_CLIPBOARD.with(|d| *d.borrow_mut() = Some(data));
    Ok(seq)
}

/// Whether the remote items Arke put on the clipboard with sequence number `seq` are still
/// there. Programs that read a format rendered on request can move the number on, so the
/// clipboard's owner window decides. Cheap; UI thread safe.
pub(crate) fn clipboard_is(seq: u32) -> bool {
    let placed = *PLACED.lock();
    let Some((placed, owner)) = placed else {
        return false;
    };
    // SAFETY: only asks which window owns the clipboard.
    let still_ours = unsafe { GetClipboardOwner() }.is_ok_and(|h| h.0.expose_provenance() == owner);
    placed == seq && owner != 0 && still_ours
}

/// Before Arke exits: takes its remote items off the clipboard if they are still there. Their
/// bytes can't be read without Arke, and Windows would try to copy every format out of the
/// object as the owner goes. Waits a moment at most.
pub(crate) fn clear_on_quit() {
    let cleared = super::lazy_clipboard::on_owner(false, Duration::from_secs(2), || {
        let Some(_data) = ON_CLIPBOARD.with(|d| d.borrow_mut().take()) else {
            return;
        };
        let placed = *PLACED.lock();
        let ours = placed.is_some_and(|(_, owner)| {
            // SAFETY: only asks which window owns the clipboard.
            unsafe { GetClipboardOwner() }.is_ok_and(|h| h.0.expose_provenance() == owner)
        });
        if ours {
            // SAFETY: OLE is up on this thread, which put the object there.
            let _ = unsafe { OleSetClipboard(None::<&IDataObject>) };
        }
    });
    if let Err(err) = cleared {
        log::debug!("remote items left on the clipboard: {err}");
    }
}

/// Drags remote items out to another program as virtual files, offering copy only. Their
/// listing must be made already ([`RemoteItems::listing`] on a background thread). UI thread,
/// like [`super::drag_out`].
pub(crate) fn drag_out(
    items: &Arc<RemoteItems>,
    image: Option<&DragImage>,
    after_lost_press: bool,
) -> Result<Option<DragOutcome>, ShellError> {
    if items.listed().is_none() {
        return Ok(None);
    }
    let data = RemoteData::create(Arc::clone(items), DROPEFFECT_COPY, false)?;
    super::drag_object_out(
        &data,
        image,
        after_lost_press,
        windows::Win32::System::Ole::DROPEFFECT_COPY,
    )
}

