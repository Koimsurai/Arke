//! Remote items on the clipboard and in drags to other programs, as virtual files (#529).
//!
//! Copying files off a phone or a server used to download them all first, so their local copies
//! could go on the clipboard as paths. Now the clipboard holds a data object that describes them
//! (`FileGroupDescriptorW`: relative names, folders, sizes, times) and hands over each file's
//! bytes as a stream (`FileContents`) when a program pastes, read from the server as the program
//! reads. Nothing is downloaded at copy time and there is no size limit. Pasting inside Arke
//! doesn't read these: Arke recognizes its own items (`RemoteShell`) and transfers the originals
//! with progress and Cancel.
//!
//! Threads: the clipboard's data object lives on the clipboard owner thread (`lazy_clipboard`),
//! which has OLE and pumps messages; a drag's lives on the UI thread for the drag. Neither waits
//! on the server for bytes: the streams are made in the multithreaded apartment
//! ([`stream_host`]), so a program's reads run on COM's threads there, each waiting only for its
//! own file. Listing the items is the one slow call the clipboard thread makes, when a program
//! first asks what they are; a drag lists them before it can leave the window, so its object
//! never waits.
//!
//! Cut: a program can't move virtual files itself, so when it reports a move (`Paste Succeeded`,
//! the shell's delete-on-paste, or `Performed DropEffect` / `Logical Performed DropEffect`), the
//! move is finished here: the originals whose bytes it read in full are deleted, and the rest as
//! their reads complete. Nothing that wasn't read in full is deleted. Drags offer copy only.
//!
//! Debug lines (target `arke::remote_clip`) say what programs ask for and set, and when a file
//! is read in full.

