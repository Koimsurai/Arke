/// What a stream reads.
struct Source {
    remotes: Arc<Remotes>,
    url: RemoteUrl,
    /// The file's name, for `Stat`.
    name: String,
    /// As listed, if known.
    size: Option<u64>,
    modified: Option<FILETIME>,
    /// Told when every byte was read (a cut's originals may go only then).
    listing: Arc<Listing>,
    index: usize,
}

/// One piece of a download: bytes, `None` at the end, or why it failed.
type Piece = Result<Option<Vec<u8>>, RemoteError>;

/// Hands what a download writes to the stream's reads.
struct Pipe(flume::Sender<Piece>);

impl std::io::Write for Pipe {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0.send(Ok(Some(buf.to_vec()))).map_err(|err| {
            // The stream was released: the program is done with the file.
            std::io::Error::new(std::io::ErrorKind::BrokenPipe, err.to_string())
        })?;
        Ok(buf.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

/// Stops a download once its stream is gone.
struct Halt(Arc<AtomicBool>);

impl TransferSink for Halt {
    fn cancelled(&self) -> bool {
        self.0.load(Ordering::Relaxed)
    }
    fn add_bytes(&self, _: u64) {}
}

/// A file being downloaded for a stream, on a thread of its own; a few pieces ahead at most.
struct Download {
    pieces: flume::Receiver<Piece>,
    stop: Arc<AtomicBool>,
    /// The piece being read, and how far.
    piece: Vec<u8>,
    at: usize,
    /// Where `piece[at]` is in the file.
    offset: u64,
    /// The whole file came.
    ended: bool,
}

impl Download {
    fn start(source: &Source) -> Self {
        let (tx, pieces) = flume::bounded::<Piece>(4);
        let stop = Arc::new(AtomicBool::new(false));
        let (remotes, url, halt) = (
            Arc::clone(&source.remotes),
            source.url.clone(),
            Arc::clone(&stop),
        );
        // If the thread can't start, the sender is dropped with the closure and the first read
        // fails (no end was sent).
        crate::explorer::spawn_thread("remote-stream", move || {
            let mut pipe = Pipe(tx.clone());
            let piece = remotes
                .download_to(&url, &mut pipe, &Halt(halt))
                .map(|()| None);
            let _ = tx.send(piece);
        });
        Self {
            pieces,
            stop,
            piece: Vec::new(),
            at: 0,
            offset: 0,
            ended: false,
        }
    }

    /// Waits for the next piece; `false` at the end of the file.
    fn fill(&mut self) -> Result<bool, HRESULT> {
        if self.ended {
            return Ok(false);
        }
        match self.pieces.recv_timeout(READ_WAIT) {
            Ok(Ok(Some(bytes))) => {
                self.piece = bytes;
                self.at = 0;
                Ok(true)
            }
            Ok(Ok(None)) => {
                self.ended = true;
                Ok(false)
            }
            Ok(Err(err)) => {
                log::info!("remote file not read for another program: {err}");
                Err(hresult_of(&err))
            }
            Err(flume::RecvTimeoutError::Timeout) => Err(HRESULT::from_win32(ERROR_TIMEOUT.0)),
            Err(flume::RecvTimeoutError::Disconnected) => Err(STG_E_READFAULT),
        }
    }
}

impl Drop for Download {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Relaxed);
    }
}

/// Where a stream is, and its download.
#[derive(Default)]
struct Position {
    pos: u64,
    download: Option<Download>,
}

impl Position {
    /// Fills `out` from the file at `pos` (less only at its end). The first read starts the
    /// download; a seek back starts it again, a seek ahead skips.
    fn read(&mut self, source: &Source, out: &mut [u8]) -> Result<usize, HRESULT> {
        if self.download.as_ref().is_some_and(|d| d.offset > self.pos) {
            self.download = None;
        }
        let download = self.download.get_or_insert_with(|| Download::start(source));
        let mut filled = 0;
        while filled < out.len() {
            if download.at == download.piece.len() {
                if !download.fill()? {
                    break;
                }
                continue;
            }
            let here = &download.piece[download.at..];
            let n = if download.offset < self.pos {
                usize::try_from(self.pos - download.offset)
                    .map_or(here.len(), |skip| skip.min(here.len()))
            } else {
                let n = here.len().min(out.len() - filled);
                out[filled..filled + n].copy_from_slice(&here[..n]);
                filled += n;
                self.pos += n as u64;
                n
            };
            download.at += n;
            download.offset += n as u64;
        }
        if !download.ended
            && download.at == download.piece.len()
            && source.size.is_some_and(|size| self.pos >= size)
        {
            // All of it, as listed: learn whether the server's file ended there too (a failure
            // shows on the next read).
            let _ = download.fill();
        }
        if download.ended
            && download.at == download.piece.len()
            && !source.listing.was_read(source.index)
        {
            source.listing.mark_read(source.index);
            log::debug!(target: LOG, "read in full by another program: {}", source.url);
            if source.listing.moved_out() {
                delete_moved(&source.remotes, source.listing.take_fully_read());
            }
        }
        Ok(filled)
    }
}

/// A remote file's bytes as a stream for another program (`FileContents`). Made in the
/// multithreaded apartment ([`make_stream`]), so the program's reads, which wait for the
/// server, run on COM's threads there.
#[implement(IStream, Agile = false)]
struct RemoteStream {
    source: Source,
    state: Mutex<Position>,
}

impl ISequentialStream_Impl for RemoteStream_Impl {
    fn Read(&self, pv: *mut std::ffi::c_void, cb: u32, pcbread: *mut u32) -> HRESULT {
        if pv.is_null() {
            return STG_E_INVALIDPOINTER;
        }
        // SAFETY: the caller's buffer has room for `cb` bytes.
        let out = unsafe { std::slice::from_raw_parts_mut(pv.cast::<u8>(), cb as usize) };
        let read = self.state.lock().read(&self.source, out);
        let (n, hr) = match read {
            Ok(n) => (n, S_OK),
            Err(hr) => (0, hr),
        };
        if !pcbread.is_null() {
            // SAFETY: the caller's count, checked above.
            unsafe { *pcbread = n as u32 };
        }
        hr
    }

    fn Write(&self, _: *const std::ffi::c_void, _: u32, _: *mut u32) -> HRESULT {
        STG_E_ACCESSDENIED
    }
}

impl IStream_Impl for RemoteStream_Impl {
    fn Seek(&self, offset: i64, origin: STREAM_SEEK, new: *mut u64) -> windows::core::Result<()> {
        let mut state = self.state.lock();
        let base = match origin {
            STREAM_SEEK_SET => 0,
            STREAM_SEEK_CUR => state.pos,
            STREAM_SEEK_END => self.source.size.ok_or(STG_E_INVALIDFUNCTION)?,
            _ => return Err(STG_E_INVALIDFUNCTION.into()),
        };
        let pos = base
            .checked_add_signed(offset)
            .ok_or(STG_E_INVALIDFUNCTION)?;
        state.pos = pos;
        drop(state);
        if !new.is_null() {
            // SAFETY: the caller's out parameter.
            unsafe { *new = pos };
        }
        Ok(())
    }

    fn SetSize(&self, _: u64) -> windows::core::Result<()> {
        Err(STG_E_ACCESSDENIED.into())
    }

    fn CopyTo(
        &self,
        _: Ref<IStream>,
        _: u64,
        _: *mut u64,
        _: *mut u64,
    ) -> windows::core::Result<()> {
        Err(E_NOTIMPL.into())
    }

    fn Commit(&self, _: &STGC) -> windows::core::Result<()> {
        Ok(())
    }

    fn Revert(&self) -> windows::core::Result<()> {
        Ok(())
    }

    fn LockRegion(&self, _: u64, _: u64, _: &LOCKTYPE) -> windows::core::Result<()> {
        Err(STG_E_INVALIDFUNCTION.into())
    }

    fn UnlockRegion(&self, _: u64, _: u64, _: u32) -> windows::core::Result<()> {
        Err(STG_E_INVALIDFUNCTION.into())
    }

    fn Stat(&self, stat: *mut STATSTG, flag: &STATFLAG) -> windows::core::Result<()> {
        if stat.is_null() {
            return Err(STG_E_INVALIDPOINTER.into());
        }
        let name = if flag.0 & STATFLAG_NONAME.0 == 0 {
            task_string(&self.source.name)
        } else {
            PWSTR::null()
        };
        // SAFETY: the caller's STATSTG; the name is the caller's to free (CoTaskMemFree).
        unsafe {
            *stat = STATSTG {
                pwcsName: name,
                r#type: STGTY_STREAM.0.cast_unsigned(),
                cbSize: self.source.size.unwrap_or(0),
                mtime: self.source.modified.unwrap_or_default(),
                grfMode: STGM_READ,
                ..Default::default()
            };
        }
        Ok(())
    }

    fn Clone(&self) -> windows::core::Result<IStream> {
        Err(E_NOTIMPL.into())
    }
}

/// `text` as a wide string in task memory, for the caller to free; null if there is no memory.
fn task_string(text: &str) -> PWSTR {
    let wide: Vec<u16> = text.encode_utf16().chain(std::iter::once(0)).collect();
    // SAFETY: allocates room for the whole string and fills it, if the allocation worked.
    unsafe {
        let ptr = CoTaskMemAlloc(wide.len() * 2).cast::<u16>();
        if ptr.is_null() {
            return PWSTR::null();
        }
        std::ptr::copy_nonoverlapping(wide.as_ptr(), ptr, wide.len());
        PWSTR(ptr)
    }
}

type Job = Box<dyn FnOnce() + Send>;

/// The thread that makes the streams, in the multithreaded apartment for the rest of the process
/// (which keeps the apartment, and the streams in it, up).
fn stream_host() -> Option<&'static flume::Sender<Job>> {
    static HOST: OnceLock<Option<flume::Sender<Job>>> = OnceLock::new();
    HOST.get_or_init(|| {
        let (jobs, queue) = flume::unbounded::<Job>();
        std::thread::Builder::new()
            .name("remote-streams".into())
            .spawn(move || {
                let _com = crate::win_virtual_drop::ComThread::init();
                while let Ok(job) = queue.recv() {
                    job();
                }
            })
            .inspect_err(|err| log::warn!("remote streams thread not started: {err}"))
            .ok()?;
        Some(jobs)
    })
    .as_ref()
}

/// A stream of `source`, made in the multithreaded apartment; on this thread, a reference to it
/// (a proxy, which hands a program a direct line to the stream).
fn make_stream(source: Source) -> windows::core::Result<IStream> {
    let host = stream_host().ok_or(E_FAIL)?;
    let (reply, answer) = flume::bounded(1);
    let job: Job = Box::new(move || {
        let stream: IStream = RemoteStream {
            source,
            state: Mutex::new(Position::default()),
        }
        .into();
        let _ = reply.send(AgileReference::new(&stream).map_err(|err| err.code()));
    });
    if host.send(job).is_err() {
        return Err(E_FAIL.into());
    }
    let made = answer
        .recv_timeout(Duration::from_secs(10))
        .map_err(|err| {
            log::warn!("remote stream not made: {err}");
            windows::core::Error::from(E_FAIL)
        })?;
    made?.resolve()
}

