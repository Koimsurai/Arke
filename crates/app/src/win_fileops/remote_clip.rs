/// The `FileGroupDescriptorW` for `items`: their count, then one descriptor each, in order (the
/// index of a file's descriptor is the index its contents are asked for by).
fn descriptor_bytes(items: &[VirtualItem]) -> Vec<u8> {
    let size = size_of::<FILEDESCRIPTORW>();
    let mut bytes = Vec::with_capacity(4 + items.len() * size);
    bytes.extend_from_slice(&u32::try_from(items.len()).unwrap_or(u32::MAX).to_le_bytes());
    for item in items {
        let one = descriptor(item);
        // SAFETY: a FILEDESCRIPTORW is plain data with no padding (packed); read as its bytes.
        let raw = unsafe { std::slice::from_raw_parts((&raw const one).cast::<u8>(), size) };
        bytes.extend_from_slice(raw);
    }
    bytes
}

fn descriptor(item: &VirtualItem) -> FILEDESCRIPTORW {
    let mut flags = FD_ATTRIBUTES.0 | FD_UNICODE.0 | FD_PROGRESSUI.0;
    let mut one = FILEDESCRIPTORW {
        dwFileAttributes: if item.is_dir() {
            FILE_ATTRIBUTE_DIRECTORY.0
        } else {
            FILE_ATTRIBUTE_NORMAL.0
        },
        ..Default::default()
    };
    if let Some(size) = item.size {
        flags |= FD_FILESIZE.0;
        one.nFileSizeHigh = (size >> 32) as u32;
        one.nFileSizeLow = size as u32;
    }
    if let Some(time) = item.modified.and_then(filetime) {
        flags |= FD_WRITESTIME.0;
        one.ftLastWriteTime = time;
    }
    // The listing leaves out longer names; the last unit stays the terminator.
    let mut name = [0u16; 260];
    for (slot, unit) in name.iter_mut().zip(item.rel.encode_utf16().take(259)) {
        *slot = unit;
    }
    one.cFileName = name;
    one.dwFlags = flags.cast_unsigned();
    one
}

fn filetime(time: SystemTime) -> Option<FILETIME> {
    let ticks = arke_core::time::filetime_from_system_time(time)?;
    Some(FILETIME {
        dwLowDateTime: ticks as u32,
        dwHighDateTime: (ticks >> 32) as u32,
    })
}

/// A medium of global memory holding `bytes`, for the caller to release.
fn global_medium(bytes: &[u8]) -> windows::core::Result<STGMEDIUM> {
    let mut mem = Global::new(bytes).map_err(|err| {
        log::info!("no memory for a clipboard format: {err}");
        windows::core::Error::from(E_OUTOFMEMORY)
    })?;
    let Some(handle) = mem.handle() else {
        return Err(E_OUTOFMEMORY.into());
    };
    mem.release();
    Ok(STGMEDIUM {
        tymed: TYMED_HGLOBAL.0.cast_unsigned(),
        u: STGMEDIUM_0 {
            hGlobal: HGLOBAL(handle.0),
        },
        pUnkForRelease: ManuallyDrop::new(None),
    })
}

/// The number in a medium of global memory (`Paste Succeeded` holds a drop effect).
///
/// # Safety
/// `medium` must be a valid medium.
unsafe fn medium_number(medium: &STGMEDIUM) -> Option<u32> {
    if medium.tymed != TYMED_HGLOBAL.0.cast_unsigned() {
        return None;
    }
    // SAFETY: the medium holds an HGLOBAL, as its tymed says; it stays locked while read.
    unsafe {
        let global = medium.u.hGlobal;
        if GlobalSize(global) < 4 {
            return None;
        }
        let ptr = GlobalLock(global).cast::<u32>();
        if ptr.is_null() {
            return None;
        }
        let value = ptr.read_unaligned();
        let _ = GlobalUnlock(global);
        Some(value)
    }
}

/// A medium's value, for debug lines: the number in it, or its size and kind.
///
/// # Safety
/// `medium` must be a valid medium.
unsafe fn describe_medium(medium: &STGMEDIUM) -> String {
    if medium.tymed != TYMED_HGLOBAL.0.cast_unsigned() {
        return format!("tymed {}", medium.tymed);
    }
    // SAFETY: the medium holds an HGLOBAL, as its tymed says.
    let (size, number) = unsafe { (GlobalSize(medium.u.hGlobal), medium_number(medium)) };
    match number {
        Some(value) if size == 4 => format!("{value:#x}"),
        Some(value) => format!("{size} bytes, starting {value:#x}"),
        None => format!("{size} bytes"),
    }
}

/// Deletes the originals of items another program moved, read in full (with the paths the panes
/// show them under), on a thread of its own; then the panes showing their folders relist.
fn delete_moved(remotes: &Arc<Remotes>, moved: Vec<(RemoteUrl, PathBuf)>) {
    if moved.is_empty() {
        return;
    }
    log::debug!(target: LOG, "deleting originals moved to another program: {moved:?}");
    let remotes = Arc::clone(remotes);
    crate::explorer::spawn_thread("remote-moved-out", move || {
        let mut folders: Vec<PathBuf> = Vec::new();
        for (url, path) in moved {
            match remotes.delete(&url, &arke_remote::NoProgress) {
                Ok(()) => log::info!("{url} moved to another program, original deleted"),
                Err(err) => log::warn!("{url} not deleted after a move to another program: {err}"),
            }
            // Relisted either way: a failed delete may have removed part of a folder.
            if let Some(folder) = path.parent()
                && !folders.iter().any(|f| f == folder)
            {
                folders.push(folder.to_path_buf());
            }
        }
        for folder in folders {
            crate::remote_shell::changed_elsewhere(folder);
        }
    });
}

/// What a program reading a file is told when the server fails.
const fn hresult_of(err: &RemoteError) -> HRESULT {
    match err {
        RemoteError::Cancelled => E_ABORT,
        RemoteError::DeviceGone => HRESULT::from_win32(ERROR_DEVICE_NOT_CONNECTED.0),
        RemoteError::Lost | RemoteError::Unreachable(_) | RemoteError::NoSuchHost(_) => {
            HRESULT::from_win32(ERROR_UNEXP_NET_ERR.0)
        }
        RemoteError::Timeout => HRESULT::from_win32(ERROR_TIMEOUT.0),
        RemoteError::NotFound => STG_E_FILENOTFOUND,
        RemoteError::Denied
        | RemoteError::Locked
        | RemoteError::NeedsLogin
        | RemoteError::LoginFailed => STG_E_ACCESSDENIED,
        _ => STG_E_READFAULT,
    }
}

