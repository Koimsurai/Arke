/// An empty scratch folder for one test.
pub(crate) fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("arke-virtual-test-{}-{name}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// Writes a drop into `stage` on a worker thread, as Arke does.
fn extract_on_worker(
    drop: VirtualDrop,
    stage: &Path,
    progress: &Arc<OpProgress>,
) -> super::Extraction {
    let stage = stage.to_path_buf();
    let progress = Arc::clone(progress);
    std::thread::spawn(move || {
        let _com = ComThread::init();
        drop.extract(&stage, &progress)
    })
    .join()
    .unwrap()
}

fn expected_stream(len: u64) -> Vec<u8> {
    (0..len).map(pattern).collect()
}

/// 2026-01-02 03:04:05 UTC as a FILETIME.
fn a_filetime() -> (FILETIME, std::time::SystemTime) {
    let unix = 1_767_323_045u64;
    let ticks = unix * 10_000_000 + 116_444_736_000_000_000;
    (
        FILETIME {
            dwLowDateTime: ticks as u32,
            dwHighDateTime: (ticks >> 32) as u32,
        },
        std::time::SystemTime::UNIX_EPOCH + std::time::Duration::from_secs(unix),
    )
}

/// Items in memory and in streams, a folder with a nested file, an empty file and two items of
/// the same name are all written where they belong, with the descriptor's size and time.
#[test]
fn writes_memory_and_stream_items_with_folders() {
    let _com = ComThread::init();
    let (filetime, time) = a_filetime();
    let mut padded = FakeItem::memory("a.txt", b"alpha");
    // The memory block is bigger than the file: only the descriptor's size is written.
    padded.body = Body::Memory(b"alphaXXXX".to_vec());
    padded.written = Some(filetime);
    let source = FakeSource::new(vec![
        padded,
        FakeItem::folder("folder"),
        FakeItem::stream("folder\\deep\\b.bin", 3000),
        FakeItem::memory("empty.txt", b""),
        FakeItem::stream("a.txt", 10),
    ]);
    let seen = source.seen();
    let data = source.data();
    let drop = VirtualDrop::take(&data).unwrap();
    assert!(!drop.reads_later());
    assert_eq!(drop.subject(), Some(("a.txt".to_owned(), 3)));
    // Read while the drop is handled, on the thread that received it.
    let here = std::thread::current().id();
    assert_eq!(
        seen.contents
            .lock()
            .iter()
            .map(|(i, t)| (*i, *t == here))
            .collect::<Vec<_>>(),
        [(0, true), (2, true), (3, true), (4, true)],
        "folders aren't asked for contents"
    );

    let stage = scratch("mixed");
    let progress = Arc::new(OpProgress::default());
    let out = extract_on_worker(drop, &stage, &progress);
    assert!(!out.cancelled);
    assert!(out.failed.is_none(), "{:?}", out.failed);
    assert_eq!(
        out.top,
        [
            stage.join("a.txt"),
            stage.join("folder"),
            stage.join("empty.txt"),
            stage.join("a (2).txt"),
        ]
    );
    assert_eq!(std::fs::read(stage.join("a.txt")).unwrap(), b"alpha");
    assert_eq!(
        std::fs::metadata(stage.join("a.txt"))
            .unwrap()
            .modified()
            .unwrap(),
        time
    );
    assert_eq!(
        std::fs::read(stage.join("folder").join("deep").join("b.bin")).unwrap(),
        expected_stream(3000)
    );
    assert_eq!(std::fs::read(stage.join("empty.txt")).unwrap(), b"");
    assert_eq!(
        std::fs::read(stage.join("a (2).txt")).unwrap(),
        expected_stream(10)
    );
    assert_eq!(progress.done.load(Ordering::Relaxed), 5);
    assert_eq!(progress.bytes.load(Ordering::Relaxed), 5 + 3000 + 10);
    let _ = std::fs::remove_dir_all(&stage);
}

/// A big stream is copied a chunk at a time, never read whole.
#[test]
fn large_streams_are_copied_in_chunks() {
    let _com = ComThread::init();
    let len = 5 * CHUNK as u64 + 123;
    let source = FakeSource::new(vec![FakeItem::stream("big.iso", len)]);
    let seen = source.seen();
    let drop = VirtualDrop::take(&source.data()).unwrap();
    let stage = scratch("large");
    let progress = Arc::new(OpProgress::default());
    let out = extract_on_worker(drop, &stage, &progress);
    assert!(out.failed.is_none() && !out.cancelled);
    assert_eq!(
        std::fs::read(stage.join("big.iso")).unwrap(),
        expected_stream(len)
    );
    assert!(seen.largest_read.load(Ordering::Relaxed) <= CHUNK);
    assert!(seen.reads.load(Ordering::Relaxed) >= 6);
    assert_eq!(progress.work_total.load(Ordering::Relaxed), len);
    assert_eq!(progress.work_done.load(Ordering::Relaxed), len);
    let _ = std::fs::remove_dir_all(&stage);
}

/// Cancel stops mid-stream: the half-written file is removed and nothing after it is written.
#[test]
fn cancel_stops_mid_stream() {
    let _com = ComThread::init();
    let progress = Arc::new(OpProgress::default());
    let mut source = FakeSource::new(vec![
        FakeItem::stream("first.bin", 4 * CHUNK as u64),
        FakeItem::memory("second.txt", b"second"),
    ]);
    source.cancel_after = Some((2, Arc::clone(&progress)));
    let drop = VirtualDrop::take(&source.data()).unwrap();
    let stage = scratch("cancel");
    let out = extract_on_worker(drop, &stage, &progress);
    assert!(out.cancelled);
    assert!(!stage.join("first.bin").exists());
    assert!(!stage.join("second.txt").exists());
    let _ = std::fs::remove_dir_all(&stage);
}

/// Names from the source can't leave the target folder or use names Windows refuses.
#[test]
fn names_stay_inside_and_are_valid() {
    assert_eq!(safe_parts(r"..\..\evil.txt"), ["evil.txt"]);
    assert_eq!(safe_parts(r"C:\Windows\x.txt"), ["C_", "Windows", "x.txt"]);
    assert_eq!(safe_parts("/etc/./passwd"), ["etc", "passwd"]);
    assert_eq!(safe_parts("con.txt"), ["_con.txt"]);
    assert_eq!(safe_parts("COM1"), ["_COM1"]);
    assert_eq!(safe_parts("a<b>:c?.txt"), ["a_b__c_.txt"]);
    assert_eq!(safe_parts("trailing. . "), ["trailing"]);
    assert_eq!(
        safe_parts("\u{5831}\u{544a}.docx"),
        ["\u{5831}\u{544a}.docx"]
    );
    assert!(safe_parts(r"..\.").is_empty());

    let _com = ComThread::init();
    let source = FakeSource::new(vec![
        FakeItem::memory(r"..\..\escaped.txt", b"x"),
        FakeItem::memory(r"..", b"nameless"),
    ]);
    let drop = VirtualDrop::take(&source.data()).unwrap();
    let stage = scratch("names");
    let out = extract_on_worker(drop, &stage, &Arc::default());
    assert_eq!(
        out.top,
        [stage.join("escaped.txt")],
        "the nameless item is skipped"
    );
    assert!(!stage.parent().unwrap().join("escaped.txt").exists());
    let _ = std::fs::remove_dir_all(&stage);
}

