/// Live: the data object File Explorer itself makes for items inside a zip folder (what a drag
/// out of a zip hands over), read on a single-threaded apartment like Arke's window thread,
/// which keeps handling messages while the worker reads through it. Only this test's own temp
/// folder is touched.
///
/// Run with `cargo nextest run -p arke-app --run-ignored only -E 'test(zip_folder)'`.
#[test]
#[ignore = "uses File Explorer's zip folders"]
fn zip_folder_items_are_taken_like_a_drop() {
    use std::io::Write as _;
    use windows::Win32::System::Com::{
        COINIT_APARTMENTTHREADED, CoInitializeEx, CoUninitialize, IDataObject,
    };
    use windows::Win32::UI::Shell::{BHID_DataObject, IShellItem, SHCreateItemFromParsingName};
    use windows::Win32::UI::WindowsAndMessaging::{
        DispatchMessageW, MSG, PM_REMOVE, PeekMessageW, TranslateMessage,
    };

    let _ = env_logger::builder().is_test(true).try_init();
    // SAFETY: this test's thread becomes an STA, as a window thread is; undone at the end.
    unsafe { CoInitializeEx(None, COINIT_APARTMENTTHREADED) }.unwrap();
    let (base, _guard) = scratch("zip");
    let zip_path = base.join("album.zip");
    let photo: Vec<u8> = (0..3 * CHUNK as u64 + 7).map(pattern).collect();
    {
        let mut zip = zip::ZipWriter::new(std::fs::File::create(&zip_path).unwrap());
        let opts = zip::write::SimpleFileOptions::default();
        zip.start_file("readme.txt", opts).unwrap();
        zip.write_all(b"read me").unwrap();
        zip.start_file("2026/photo.bin", opts).unwrap();
        zip.write_all(&photo).unwrap();
        zip.finish().unwrap();
    }
    let data_of = |inner: &str| -> IDataObject {
        let path = zip_path.join(inner);
        let wide: Vec<u16> = path
            .to_string_lossy()
            .encode_utf16()
            .chain(std::iter::once(0))
            .collect();
        // SAFETY: a null-terminated parsing name; the item binds to its data object.
        unsafe {
            let item: IShellItem = SHCreateItemFromParsingName(PCWSTR(wide.as_ptr()), None)
                .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
            item.BindToHandler(None, &BHID_DataObject).unwrap()
        }
    };

    for (inner, expect) in [
        ("readme.txt", vec![("readme.txt", b"read me".to_vec())]),
        ("2026", vec![(r"2026\photo.bin", photo)]),
    ] {
        let data = data_of(inner);
        let paths = gpui_windows::drop_paths(&data);
        assert!(
            paths.as_deref().is_some_and(super::is_virtual),
            "a zip item is handed over as a virtual file: {paths:?}"
        );
        let drop = VirtualDrop::take(&data).unwrap();
        log::info!("{inner}: read later: {}", drop.reads_later());
        let stage = base.join(format!("stage-{inner}"));
        std::fs::create_dir_all(&stage).unwrap();
        let progress = Arc::new(OpProgress::default());
        let worker = {
            let stage = stage.clone();
            let progress = Arc::clone(&progress);
            std::thread::spawn(move || {
                let _com = ComThread::init();
                drop.extract(&stage, &progress)
            })
        };
        // Keep handling messages, as Arke's window thread does, while the worker calls back
        // into this apartment.
        while !worker.is_finished() {
            let mut msg = MSG::default();
            // SAFETY: plain message pumping on this thread.
            unsafe {
                while PeekMessageW(&raw mut msg, None, 0, 0, PM_REMOVE).as_bool() {
                    let _ = TranslateMessage(&raw const msg);
                    DispatchMessageW(&raw const msg);
                }
            }
            std::thread::sleep(std::time::Duration::from_millis(2));
        }
        let out = worker.join().unwrap();
        assert!(out.failed.is_none(), "{:?}", out.failed);
        assert!(!out.cancelled);
        for (rel, bytes) in expect {
            assert_eq!(std::fs::read(stage.join(rel)).unwrap(), bytes, "{rel}");
        }
    }
    // SAFETY: pairs with CoInitializeEx above.
    unsafe { CoUninitialize() };
}
